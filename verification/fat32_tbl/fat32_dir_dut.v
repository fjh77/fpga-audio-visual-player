// 【验证副本】本文件是 hardware/.../hdl_source/fat32_dir.v 的拷贝，
//   仅把模块名改成 fat32_dir_dut 以便单独例化。
//   修改 RTL 后请同步本文件。
//=============================================================================
// 文件名  : fat32_dir.v
// 功能    : FAT32 阶段 1 —— 读 BPB -> 定位根目录 -> 解析全部短目录项
//           输出一张「文件名(原始 8.3 的 11 字节) + 首簇号(32bit) + 大小(32bit)
//           + 属性(8bit)」表
//
// 本模块不做什么（留给阶段 2/3，不要顺手加进来）
// ------------------------------------------------
//   * 不跟文件的簇链、不读文件数据 —— 本模块到"首簇号 + 大小"为止
//   * 不接 SPI、不改任何现有模块（sd_card_bmp.v / top.v 一个字没动）
//   * 不解析长文件名(LFN)。镜像里的 8.3 短名就是最终名字；LFN 槽位按"属性字节
//     == 0x0F"整条跳过，不进文件表（见 rec_ok 的说明）
//
// 为什么做成"自包含 + 请求扇区"接口
// ----------------------------------
//   阶段 2 会把它挂到读卡通路上；验证时只要喂它一块假扇区源（文件 ROM/BRAM）
//   就能跑，完全不必模拟 SPI 和 SD 协议。所以这里只定义一层握手：
//      我输出「请给我扇区 N」 -> 你按序还我 512 个字节
//
// 两条硬约束（都是踩过坑总结出来的，不要"顺手简化"掉）
// ============================================================================
// 约束 1：目录项名字匹配必须做 sticky 锁存
// -----------------------------------------
//   反面教材见 tools/fat32_sim/README.md：第三方参考读卡器 sd_file_reader.v
//   把"找到文件"做成了瞬时标志—— 对每个短目录项跑一遍比较，不匹配就
//   file_found<=0；而主状态机只在整扇区读完时才看 file_found。
//   于是同一扇区里"最后一个同长度目录项"的比较结果会把前面的覆盖掉。
//   实测：根目录 01.BMP + 01.WAV（名字等长）时，目标 01.BMP -> 读到 0 字节。
//   我们的卡上全是 01.BMP/01.WAV 这种等长名，照抄必然踩。
//
//   本模块的做法：给每个目录项一个"粘住不放"的匹配标志（stick）
//       * 目录项第 0 字节（项内偏移 0）处清零 —— 开始新的一项
//       * 项内偏移 10（第 11 个名字字节，也是最后一个）那一拍：
//         11 个字节全中 -> 置 1
//       * 只有下一个目录项的第 0 字节能把它清零
//   匹配结果一直保持到本目录项在偏移 11 处被写进文件表，谁都清不掉。
//
// 约束 2：首簇号必须 32 位，必须读 FstClusHI
// ------------------------------------------
//   目录项偏移 +20 是 FstClusHI(高 16 位)，+26 是 FstClusLO(低 16 位)：
//       首簇 = {FstClusHI, FstClusLO}
//   参考设计只取低 16 位，是它的局限。我们卡上 02.BMP 首簇 56626 就已经
//   超 16 位了，只读低 16 位会跑到别的簇上去，所以这里两个字节对都收。
//
// 位宽（本项目踩过多次的坑，全部显式写死）
// ----------------------------------------
//   LBA 最宽 28~29 位（分区起始 2048 + 数据区偏移 1056 + 簇偏移）。
//   簇偏移 = (簇号 - 2) << log2(SecPerClus)，SecPerClus 是 2 的幂（<=128），
//   用移位实现；中间结果一律用 40 位接住，确认高位没超才截到 32 位。
//   所有字面量都写明确位宽（连 0 和 1 也写）。
//
// 四个"必须这样写"的实现要点（都是本模块调试时真踩过的坑，含真实卡）
// ============================================================================
// (A) o_rd_lba 必须与 o_rd_req 同拍、纯组合
//     o_rd_req 是状态的组合函数，外部在"o_rd_req 有效的那一拍"就采 o_rd_lba。
//     如果 o_rd_lba 是另外的寄存器，就会出现"请求已经发了、扇区号还是旧值"。
//     本模块仿真里就因此把 DBR 请求发到了扇区 0。
//     所以 o_rd_lba 直接从 rsec/rsec_cnt 组合算出来。
//
// (B) 切换扇区后要隔一拍再发请求（S_SET 状态）
//     换扇区时 part_lba / root_base 是在 S_CHK 那一拍才写进寄存器的，
//     而 o_rd_lba 是它们的组合函数。若从 S_CHK 直接跳 S_REQ，
//     S_REQ 第一拍的 o_rd_lba 还是旧值（0）—— 于是"去读根目录"变成了
//     "去读扇区 0"，一个文件都解不出来。隔一拍（S_SET）就稳了。
//
// (C) 名字字节的"累积"与"提交"要用不同的使能条件，不能都用 rec_ok
//     rec_ok 依赖 att_q（本目录项的属性字节），而 att_q 要到偏移 11
//     才写进来。所以在偏移 0/1 那两拍，att_q 还是上一条目录项的值：
//       * 用 rec_ok 门控 match_acc -> 累积器没有初值，永远匹配不上
//       * 用 rec_ok 门控 nm_buf   -> 前几个字符丢失，名字错位
//     正确做法：累积用 id_ok（只依赖 fst0 与 att_q 是否 LFN，偏移 1 就正确），
//     只有在偏移 11 提交记录那一步才用 rec_ok 过滤。
//     另外，写字段的顺序也要注意：同一个 always 块里对同一寄存器多次赋
//     非阻塞值，最后一次生效 —— 所以"偏移 0 的清零"要写在"置位"之前。
//
// (D) 判"本项是不是文件"必须用本项的属性字节，不能用 att_q 寄存器
//     att_q 在偏移 11 那一拍写进去、偏移 12 才看得见，而 rec_commit 就在
//     偏移 11 判定。若那里读 att_q，判的是上一条目录项的属性 —— 整个
//     "本项是不是文件"的判定错位一条。合成镜像上所有短目录项属性都是 0x20，
//     错位恰好看不出来；真实 TF 卡（tf_card_disk1_20261006_233449.img）上
//     00_1.BMP 前面正好是一条已删除的 SYSTEM~1（属性 0x16 含目录位），于是
//     00_1.BMP 被当目录丢掉，而紧跟 03_4.BMP 的 LFN 槽位（上一条属性 0x20）
//     反被当成文件写进表里。修法：att_eff = (偏移 11) ? cur : att_q。
//     同理，LFN 槽位只认属性字节 == 0x0F，不要去认首字节（首字节是
//     序号 0x01~0x14 / 0x41~0x54，永远不是 0x0F；老版本那个"首字节 == 0x0F
//     就进 LFN 状态"的判断既抓不到 LFN，又会在序号为 15 的长名槽位上误触发，
//     把紧随其后的真文件当 LFN 丢掉）。
//
// (E) "簇号 -> 扇区"的移位量必须真的由 SecPerClus 解出来
//     spc_lg2 以前只声明、只复位，从来没有被赋过值，一直是 0 —— 等于把
//     每簇扇区数硬当成 1。两张验证镜像的根目录首簇都是 2，而 (2-2)<<任何值
//     都是 0，所以一直没暴露。RootClus != 2 的卡（规范允许，Windows 格式化的
//     卡上通常就是 2，但别的工具可能是别的值）会直接把根目录算到数据区起始。
//     现在在"签名与几何合法性"那个组合块里用 case 把 spc_lg2 解出来，
//     并且它是 spc_lg2 的唯一驱动。
//
// (F) 2026-10 新增：等扇区数据的超时必须区分"排队"和"传输"
//     真硬件现象（阶段 3b 上板 HDMI 全黑）：err_code=12（ERR_SECTOR_TO）。
//     根因：本模块的 tmo_cnt 以前从发出请求（进 S_REQ）就开始计时，
//     而请求发出去之后可能一直在 sd_arbiter3 里排队—— bmp 是最高优先级，
//     它一读就是一整张图（1801 扇区 ≈ 0.85 秒），而阈值只有 16384 拍
//     （= 163.84µs @100MHz）—— 排队时间被错算成传输超时，必然误报。
//
//     修法：新增输入 i_granted（来自 sd_arbiter3 的 o_grant_fat），
//       * tmo_cnt   只在 i_granted=1（卡确实归我）期间累加 —— 传输超时；
//       * tmo_all_cnt 不看授权、从请求发出起累加 —— 只防"永远排不上队"，
//         阈值 TO_LIMIT_ALL 取 2 秒（远大于一次整图装载 0.85 秒）。
// 为什么不能只把阈值放大就完事
//       排队时间在设计上可以长到"一整张图的装载时间"，而传输超时必须在
//       断流几十毫秒内就报出来（否则整个启动被一个死掉的读卡拖住）。
//       两个时间尺度差了 4 个数量级，一个阈值不可能同时满足 —— 必须分开。
// 兼容性 没有仲裁器的场合（单元仿真）把 i_granted 接 1'b1，
//       行为就退化成修复前（一直计时），所以老 tb 的语义不会被破坏。
//=============================================================================

module fat32_dir #(
    // 文件表容量：卡上 8 个文件（01..04 的 BMP + WAV），留一倍余量
    parameter        MAX_FILES  = 10,
    // 一个目录项 32 字节；写成参数，免得正文里散落魔数
    parameter [5:0]  DIR_ENT_B  = 6'd32,
    //-------------------------------------------------------------------------
    // 扇区数据超时（拍）—— 2026-10 修复：语义变了，值也必须跟着改
    //
    // 语义（修复后）：这是已经被仲裁器授权用卡之后、"连着 TO_LIMIT 拍
    //   没有收到任何数据字节"才算超时。计数器每收到一个字节就清零，
    //   所以它实际约束的是两个字节之间的最大间隔以及授权到第一个
    //   字节之间的等待】，而不是"一整个扇区的总时间"。
    //   （排队等仲裁的时间不计入这里，见 TO_LIMIT_ALL 与 i_granted。）
    //
    // 为什么默认值从 16384 改成 2_000_000（= 20ms @100MHz）：
    //   ① 16384 拍 @100MHz = 163.84µs，这个数恰好等于 25MHz SPI 传完
    //      512 字节纯数据的时间（512×8/25MHz = 163.84µs）—— 也就是说
    //      它连"命令阶段 + 卡内部读延迟 + 数据令牌"的余量都没有，
    //      是原设计按"25MHz 主频"估的（注释里那两个数就是矛盾的）。
    //   ② 授权之后真正需要覆盖的是卡的首次数据延迟：CMD17 发完要等
    //      卡的响应(N_CR ≤ 8 字节) + 数据令牌，SD 规范允许卡的读访问时间
    //      长得多（冷卡、刚上电的第一次读尤其明显）。实测 3a 能过、
    //      3b（sd_init_done 一起来就解析，卡是"冷的"）过不去，正是这一侧。
    //   ③ 20ms = 约 40 个扇区的传输时间（按注释里实测的 ≈470µs/扇区），
    //      比一个扇区宽 100 倍以上；同时远小于"一张图装载 0.85 秒"，
    //      所以它依然能当看门狗用（真断流 20ms 就报错，不会拖住整个启动）。
    //   ④ 上限不能取到"和 bmp 一张图的 0.85 秒同量级"——那会让看门狗
    //      比它保护的对象还慢（本项目 wav_player 的 10 秒兜底就踩过
    //      "兜底比被保护对象更早触发/更晚触发"这一类坑）。授权期间本来
    //      就不该等那么久，20ms 足够。
    parameter [31:0] TO_LIMIT   = 32'd2000000,
    //-------------------------------------------------------------------------
    // TO_LIMIT_ALL：从"发出请求"起算的总等待上限（含排队时间）
    //
    // 为什么还需要这个（第 1 层修好了会不会挂死？）：
    //   把排队时间排除出超时之后，理论上"永远排不上队"就永远不报错了 ——
    //   这是新的挂死风险（表现为：FAT 一直不 done -> bmp_ready 一直不拉高 ->
    //   一张图都不装 -> 黑屏且没有错误码，比报错更难查）。
    //   所以保留一个大得多的总等待兜底：排队 + 传输合计超过 TO_LIMIT_ALL
    //   仍然报 ERR_SECTOR_TO，让错误可见。
    //
    // 为什么取 2 秒（= 2×10^8 拍 @100MHz）：
    //   必须明显大于"最长的合法排队" = 一次 bmp 整图装载 ≈ 0.85 秒
    //   （1801 扇区）× 安全系数 2.3。取 2 秒之后：
    //     * 正常情况（排一个扇区、甚至排一整张图）绝不会误报；
    //     * 真死锁 2 秒内报出来，用户翻到诊断页就能看到 err=12。
    //   它比 fat32 之外的"装载看门狗 3 秒"（sd_card_bmp）更早，层次是对的。
    parameter [31:0] TO_LIMIT_ALL = 32'd200000000
)(
    input               clk,            // 系统时钟，25MHz，与读卡/视频同一时钟域
    input               rst_n,          // 异步复位，低有效（与本工程其余模块一致）

    // ---- 启动与状态 ----
    input               start,          // 单拍脉冲启动一次解析；完成后要复位才能再启动
    output              busy,           // 1 = 解析进行中（含等扇区数据的时间）
    output              done,           // 1 = 解析完成（电平保持，之后可自由读文件表）
    output reg [3:0]    err_code,       // 错误码，0 = 无错；含义见 localparam

    // ---- 扇区读取握手（外部只负责"按号取 512 字节"）----
    output reg [31:0]   o_rd_lba,       // 请求读哪个绝对扇区（LBA，512 字节/扇区）
    output reg          o_rd_req,       // 1 = 正在请求该扇区（电平保持到数据回来）
    input      [7:0]    i_data,         // 扇区数据，字节流
    input               i_data_valid,   // 1 = 本拍 i_data 有效
    input               i_data_last,    // 1 = 本拍是这 512 字节的最后一个（可恒 0）

    // ---- 文件表（组合读出，无需时钟）----
    output reg [4:0]    o_count,        // 解析到的文件条数（0 ~ MAX_FILES）
    input      [3:0]    i_tbl_idx,      // 读表下标 0~15
    output     [87:0]   o_tbl_name,     // 该条目的 8.3 名字原始 11 字节（空格 0x20 填充）
    output     [31:0]   o_tbl_cluster,  // 该条目的首簇号 {FstClusHI, FstClusLO}
    output     [31:0]   o_tbl_size,     // 该条目的文件大小（字节）
    output     [7:0]    o_tbl_attr,     // 该条目的属性字节（本卡上是 0x20）

    // ---- 目标文件名（阶段 2 由"选片/选曲"状态写进来）----
    input               tgt_we,         // 1 = 本拍写入新目标名（不接就一直是默认 01.BMP）
    input      [87:0]   tgt_name,       // 8.3 原始 11 字节（无 '.'，不足处填 0x20）

    // ---- 卷几何（阶段 2：fat32_file.v 直接拿这四个信号跟簇链）----
    // 这四个是"正式输出"，与下面的 dbg_* 是同一份数据的两个出口
    //   做成正式输出而不让阶段 2 去猜/重算的原因：几何一旦算错，阶段 2 读到的
    //   就是别的扇区，而"读错扇区"在数据流上是看不出来的（只会是一堆看着合法
    //   的字节）。让阶段 2 只用这里算好的值，几何只有一处实现、一处验证。
    output     [31:0]   o_fat_lba,      // FAT1 起始绝对扇区
    output     [31:0]   o_data_lba,     // 数据区起始绝对扇区
    output     [7:0]    o_sec_per_clus, // 每簇扇区数（BPB_SecPerClus）
    output     [4:0]    o_spc_lg2,      // log2(每簇扇区数)，簇内扇区偏移用

    // ---- 现场调试（数码管/LED）：解析中算出来的关键扇区号 ----
    output reg [31:0]   dbg_part_lba,   // MBR 分区起始 LBA
    output reg [31:0]   dbg_data_lba,   // 数据区起始绝对扇区
    output reg [31:0]   dbg_root_lba,   // 根目录首簇的绝对首扇区
    output reg [31:0]   dbg_fat_lba,    // FAT1 起始绝对扇区
    output reg [15:0]   dbg_secs,       // 本次一共成功收了多少个扇区（含 MBR/DBR）
    output reg [7:0]    dbg_part_type,  // MBR 分区表项的类型字节（0x0C = FAT32 LBA）

    // ---- 临时诊断（2026-10：定位"真硬件上根目录读成 0x00"） ----
    //   这三个是"读数到底对不对"的直接证据，只做观测，不参与任何判定逻辑，
    //   所以它们出错也不会影响解析结果（诊断代码必须是无副作用的）。
    output reg [7:0]    dbg_root_b0,    // 根目录首扇区收到的第 1 个字节
    output reg [7:0]    dbg_root_b1,    // 根目录首扇区收到的第 2 个字节
    output reg [15:0]   dbg_rx_bytes,   // 本次一共收了多少个数据字节

    //-------------------------------------------------------------------------
    // 2026-10 超时修复新增：本路"已被仲裁器授权用卡"
    //   1 = 卡现在确实归我（sd_arbiter3 已批准本次请求），
    //   0 = 我的请求还挂在仲裁器上排队。
    // 只参与超时计时，不参与任何数据/状态判定
    // 没有仲裁器的场合（例如单元仿真 tb）请直接接 1'b1
    //     （接 1'b1 = 退化成修复前的行为：只要在等数据就一直计时）
    input               i_granted
);

    //-------------------------------------------------------------------------
    // 错误码（0 = 成功）。给数码管看，每个码对应一个明确的失败点。
    //-------------------------------------------------------------------------
    localparam [3:0] ERR_NONE      = 4'd0,   // 无错
                     ERR_MBR_SIG   = 4'd1,   // 扇区 0 缺 0x55AA 签名
                     ERR_PART_EMPTY= 4'd2,   // MBR 分区表项类型为 0（空项）
                     ERR_DBR_SIG   = 4'd3,   // DBR 缺 0x55AA 签名
                     ERR_BPS       = 4'd4,   // BPB_BytsPerSec != 512（本模块只支持 512）
                     ERR_SPC       = 4'd5,   // BPB_SecPerClus 不是 2 的幂 / 越界
                     ERR_ROOTENT   = 4'd6,   // BPB_RootEntCnt != 0（这不是 FAT32）
                     ERR_FATSZ     = 4'd7,   // FATSz16/FATSz32 全 0，定位不到数据区
                     ERR_ROOTCLU   = 4'd8,   // 根目录首簇 < 2（非法）
                     ERR_OVF       = 4'd9,   // 文件数超过表容量 MAX_FILES
                     ERR_LBA_RANGE = 4'd10,  // 关键扇区号算出来超过 32 位
                     ERR_CHAIN_LEN = 4'd11,  // 根目录簇内扇区读完仍未见 00 结束项
                     // 等扇区数据超时。2026-10 修复后语义分两种，都报这个码：
                     //   ① 已被授权后连续 TO_LIMIT 拍（20ms）没有数据字节
                     //   ② 从发出请求算起总等待超过 TO_LIMIT_ALL（2 秒，防饥饿）
                     ERR_SECTOR_TO = 4'd12;

    //-------------------------------------------------------------------------
    // 主状态机
    //   S_IDLE : 等 start
    //   S_REQ  : o_rd_req 拉高，等第一个数据字节（扇区号由组合逻辑给出）
    //   S_READ : 收 512 字节，边收边解析
    //   S_CHK  : 本扇区收完，校验签名/BPB，并锁存下一段要用的几何参数
    //   S_SET  : 让刚锁存的参数落定一拍（见文件头要点 B）
    //   S_DONE : 收尾，完成
    //-------------------------------------------------------------------------
    localparam [2:0] S_IDLE = 3'd0,
                     S_REQ  = 3'd1,
                     S_READ = 3'd2,
                     S_CHK  = 3'd3,
                     S_SET  = 3'd4,
                     S_DONE = 3'd5;

    reg [2:0] st;

    assign busy = (st != S_IDLE) && (st != S_DONE);
    assign done = (st == S_DONE);

    //-------------------------------------------------------------------------
    // 扇区序号
    //   0 = 扇区 0 (MBR)
    //   1 = 分区起始扇区 (DBR/BPB)
    //   2 = 根目录扇区（绝对扇区号 = 根目录首簇首扇区 + rsec_cnt）
    //-------------------------------------------------------------------------
    reg [1:0]  rsec;
    reg [31:0] rsec_cnt;     // 根目录当前簇内已读的扇区数

    //-------------------------------------------------------------------------
    // 从 BPB 解出来的几何参数
    //-------------------------------------------------------------------------
    reg [15:0] bps;          // BPB_BytsPerSec（本模块只接受 512）
    reg [7:0]  spc;          // BPB_SecPerClus（2 的幂）
    reg [4:0]  spc_lg2;      // log2(spc)，用于移位；spc 最大 128 -> 7
    reg [15:0] rsvd;         // BPB_RsvdSecCnt
    reg [7:0]  nfat;         // BPB_NumFATs
    reg [15:0] root_ent;     // BPB_RootEntCnt（FAT32 必须为 0）
    reg [31:0] fatsz32;      // BPB_FATSz32
    reg [15:0] fatsz16;      // BPB_FATSz16
    reg [31:0] root_clus;    // BPB_RootClus

    reg [31:0] part_lba;     // 分区起始绝对扇区（MBR 收完时锁存）
    reg [31:0] fat_lba;      // FAT1 起始绝对扇区
    reg [31:0] data_lba;     // 数据区起始绝对扇区
    reg [31:0] root_base;    // 根目录首簇的绝对首扇区

    // MBR 分区表第 0 项（偏移 446 起 16 字节）
    reg [7:0]  part_type;    // +4  分区类型（0x0C = FAT32 LBA）
    reg [31:0] part_start;   // +8  起始 LBA
    reg [31:0] part_sectors; // +12 扇区数

    // 两个 0x55AA 签名的两字节
    reg [7:0]  mbr_b510, mbr_b511;
    reg [7:0]  dbr_b510, dbr_b511;

    // 组合：合法性判断（写在信号声明之后，避免 TD 对前向引用报错）
    reg        mbr_sig_ok;
    reg        dbr_sig_ok;
    reg        spc_ok;

    // 组合临时量：40 位，用来接住加/移位的中间结果，防 32 位溢出
    reg [39:0] data_off_x;   // rsvd + nfat * fatsz32
    reg [39:0] clu_off_x;    // (root_clus - 2) << spc_lg2
    reg [39:0] fat_base_x;   // part_lba + rsvd
    reg [39:0] data_base_x;  // part_lba + data_off_x
    reg [39:0] root_base_x;  // data_base_x + clu_off_x
    reg        lba_range_bad;

    //-------------------------------------------------------------------------
    // 逐字节解包寄存器（边收边解析，不整扇区缓存，省 BRAM）
    //
    //   bcnt 语义 = 正在处理的字节在扇区内的偏移，0~511。
    //     S_REQ 收到第一个字节（偏移 0）时 bcnt 就是 0，解析完进 S_READ 并置 1；
    //     S_READ 每拍解析偏移 bcnt，然后 +1；bcnt==511 那拍是扇区末字节。
    //-------------------------------------------------------------------------
    reg [9:0]  bcnt;

    reg [7:0]  cur;          // 当前字节（寄存一份，免得组合里反复引 i_data）
    reg [7:0]  fst0;         // 目录项首字节（判 00/E5 用）
    reg [7:0]  att_q;        // 目录项属性字节（本项属性，偏移 11 那一拍写进来）
    reg [7:0]  att_eff;      // 本项属性的"当前值"：偏移 11 那拍就是本字节
    reg        end_q;        // 已经遇到 0x00 结束项（本扇区后面全是空的）

    reg [87:0] nm_buf;       // 当前目录项名字 11 字节（字节 0 在最高位）
    reg [7:0]  b20, b21;     // FstClusHI 的两字节（约束 2）
    reg [7:0]  b26, b27;     // FstClusLO 的两字节
    reg [7:0]  b28, b29;     // 文件大小低 16 位
    reg [7:0]  b30, b31;     // 文件大小高 16 位

    // 约束 1 的 sticky 标志
    reg        stick;        // 本目录项 11 个名字字节全部匹配上了（粘住不放）
    reg        match_acc;    // 本目录项"到目前为止"每一个名字字节都对上了
    reg        ent_ok;       // 本目录项是"活项"（首字节既不是 00 也不是 E5）
    reg        pend_rec;     // 本目录项是一条有效文件记录（名字已写表，等补簇号/大小）
    reg [3:0]  rec_idx;      // 文件表写入下标（一条记录分三拍写，写完才推进）
    wire       dir_mode;     // 1 = 当前在读根目录扇区（rsec==2），才做目录项解析

    // 组合：名字匹配 / 记录判定
    reg [7:0]  tf_byte;      // 目标文件名在当前字母位置上的那一个字节
    reg        rec_ok;       // 本目录项是"要记录的文件"
    reg        name_wr;      // 当前字节要收进 nm_buf
    reg        rec_commit;   // 偏移 11：判定"本项是有效文件"，立 pend_rec
    reg        rec_write;    // 偏移 0：把上一条记录完整写进文件表
    reg        acc_nx;       // match_acc 的组合下一值（见下面的累积器 always）
    reg        tmo_hit;      // 等扇区数据超时（组合）
    wire       cur_rd_valid; // 本拍确实在处理一个有效字节

    //-------------------------------------------------------------------------
    // 目标文件名
    //   存的是 8.3 原始 11 字节形式：名字不足 8 位用 0x20 空格补齐，
    //   目录项里本来就没有 '.' 字符（第 8 字节是空格，不是点）。
    //     01.BMP -> 30 31 20 20 20 20 20 20 42 4D 50
    //     01.WAV -> 30 31 20 20 20 20 20 20 57 41 56
    //   默认 01.BMP：它是根目录第 0 项（不是最后一项），正好是最容易暴
    //   "瞬时标志"bug 的那个目标 —— 详见 tools/fat32_sim/README.md。
    //-------------------------------------------------------------------------
    reg [87:0] target_name;

    initial target_name = 88'h3031202020202020424D50;   // "01" + 6 空格 + "BMP"

    //-------------------------------------------------------------------------
    // 文件表：16 条 x 160 位。分四个数组而不是一个大向量数组，理由：
    //   * 读侧本来就是四条独立总线，分开放映射到 BRAM 更自然
    //   * 免去 {name, b21,b20,b27,b26, ...} 这种"拼接宽度由上下文决定"的写法
    //     （正是 verilog_width_check.py 要拦的那类隐患）
    //-------------------------------------------------------------------------
    // 表深度跟着 MAX_FILES 走。
    //   注意语义沿用原实现：容量是 MAX_FILES 个槽位（下标 0 ~ MAX_FILES-1），
    //   但 rec_idx 走到最后一个槽位时不再写入（报 ERR_OVF），
    //   所以实际可收纳的有效条目是 MAX_FILES-1 个。
    //   MAX_FILES=16 时的历史行为是"最多 15 个文件"，换成 10 即"最多 9 个"，
    //   语义一一对应，不存在 off-by-one 变化。
    //   注意：这里不要在 MAX_FILES 上做位选（它是无位宽 parameter，
    //   位选行为在综合器与仿真器之间不保证一致）；直接相减，由
    //   TBL_LAST 自身的 [4:0] 位宽完成截断。MAX_FILES 需 ≤ 16。
    localparam [4:0] TBL_LAST = MAX_FILES - 5'd1;

    reg [87:0] tbl_name    [0:MAX_FILES-1];
    reg [31:0] tbl_cluster [0:MAX_FILES-1];
    reg [31:0] tbl_size    [0:MAX_FILES-1];
    reg [7:0]  tbl_attr    [0:MAX_FILES-1];

    assign o_tbl_name    = tbl_name[i_tbl_idx];
    assign o_tbl_cluster = tbl_cluster[i_tbl_idx];
    assign o_tbl_size    = tbl_size[i_tbl_idx];
    assign o_tbl_attr    = tbl_attr[i_tbl_idx];

    // 只有读根目录扇区时才做目录项/BPB 的字段解析（互相不会同时发生）
    assign dir_mode = (rsec == 2'd2);

    //-------------------------------------------------------------------------
    // 阶段 2 要用的卷几何：直接引内部寄存器，一份数据两个出口。
    // 用 assign 引出去（而不是新建 reg 再赋值）
    //   这样它们不占额外的寄存器、也不可能与内部值不一致；而且 spc_lg2
    //   仍然只有那个组合 case 块一个驱动（多一个 always 块赋值就会被
    //   verilog_lint.py 判为多驱动）。
    //-------------------------------------------------------------------------
    assign o_fat_lba      = fat_lba;
    assign o_data_lba     = data_lba;
    assign o_sec_per_clus = spc;
    assign o_spc_lg2      = spc_lg2;

    //-------------------------------------------------------------------------
    // 组合：签名与几何合法性 + SecPerClus -> log2(SecPerClus)
    //-------------------------------------------------------------------------
    always @(*) begin
        mbr_sig_ok = (mbr_b510 == 8'h55) && (mbr_b511 == 8'hAA);
        dbr_sig_ok = (dbr_b510 == 8'h55) && (dbr_b511 == 8'hAA);
        // SecPerClus 必须是 2 的幂且落在 [1,64]（bit7=0 排除 >=128 的越界值）
        spc_ok = (spc != 8'd0) && ((spc & (spc - 8'd1)) == 8'd0) && (spc[7] == 1'b0);

        // 簇号 -> 扇区的移位量（clu_off_x 用它）
        //   这一段以前根本没写：spc_lg2 一直停在复位值 0，等于把"每簇扇区数"
        //   硬当成 1。两张验证镜像的根目录首簇都是 2，而 (2-2)<<任何值 都是 0，
        //   所以一直没暴露；一旦 RootClus != 2（规范完全允许），根目录就会算到
        //   数据区起始去 —— 换一张卡就挂。
        //   这里用 case 而不是 for 循环求 log2：写法显式、综合器与 iverilog 都认。
        //   注意本块是 spc_lg2 的唯一驱动（复位分支里那句已删掉），
        //   否则同一个 reg 会被两个 always 块赋值（verilog_lint.py 会报，综合器不认）。
        case (spc)
        8'd1:    spc_lg2 = 5'd0;
        8'd2:    spc_lg2 = 5'd1;
        8'd4:    spc_lg2 = 5'd2;
        8'd8:    spc_lg2 = 5'd3;
        8'd16:   spc_lg2 = 5'd4;
        8'd32:   spc_lg2 = 5'd5;
        8'd64:   spc_lg2 = 5'd6;
        8'd128:  spc_lg2 = 5'd7;
        default: spc_lg2 = 5'd0;
        endcase
    end

    //-------------------------------------------------------------------------
    // 组合：扇区号 + 超时 + 几何中间量
    //
    //   数据区起始(相对) = RsvdSecCnt + NumFATs * FATSz
    //   簇 N 起始绝对扇区 = 分区起始 + 数据区起始(相对) + (N - 2) * SecPerClus
    //   根目录第 k 个扇区  = 根目录首簇的首扇区 + k
    //
    //   nfat(8bit) * fatsz32(32bit) 最大 40 位，显式用 40 位中间量接住；
    //   确认高位没超才截到 32 位，绝不静默截断成"另一个扇区号"。
    //
    // 这三个中间量只依赖"已经稳定"的寄存器
    //   data_base_x 用 part_lba（MBR 阶段就锁好了），不引用 data_lba；
    //   root_base_x 用 data_base_x，同样不引用 data_lba。
    //   早先写成 data_lba + clu_off_x，而 data_lba 正好在同一拍才被赋值，
    //   于是 root_base_x 恒等于 0（根目录被当成扇区 0 去读）。
    //
    // 两个超时计数器（2026-10 修复）
    //   tmo_cnt     : 只统计已授权之后的断流拍数 —— 真正的传输超时
    //   tmo_all_cnt : 不看授权、只要在等数据就累加 —— 防饥饿的总等待兜底
    //   两个名字都在这里声明、在下面唯一的时序块里驱动（本项目红线：
    //   同一个 reg 只能由一个 always 块驱动）。
    //-------------------------------------------------------------------------
    reg [31:0] tmo_cnt;
    reg [31:0] tmo_all_cnt;

    always @(*) begin
        data_off_x  = {24'd0, rsvd} + ({32'd0, nfat} * fatsz32);
        clu_off_x   = ({8'd0, root_clus} - 40'd2) << spc_lg2;
        fat_base_x  = {8'd0, part_lba} + {24'd0, rsvd};
        data_base_x = {8'd0, part_lba} + data_off_x;
        root_base_x = data_base_x + clu_off_x;

        lba_range_bad = (|fat_base_x[39:32]) || (|data_base_x[39:32]) ||
                        (|root_base_x[39:32]);

        // ---- 请求哪一个扇区（纯组合，与 o_rd_req 同拍有效，见要点 A）----
        if (rsec == 2'd0)
            o_rd_lba = 32'd0;                       // MBR 永远在扇区 0
        else if (rsec == 2'd1)
            o_rd_lba = part_lba;                    // DBR = 分区起始扇区
        else
            o_rd_lba = root_base + rsec_cnt;        // 根目录第 k 个扇区

        o_rd_req = (st == S_REQ);

        // 两种超时任一命中就报错（语义见 TO_LIMIT / TO_LIMIT_ALL 注释）
        tmo_hit = (tmo_cnt >= TO_LIMIT) || (tmo_all_cnt >= TO_LIMIT_ALL);
    end

    //-------------------------------------------------------------------------
    // 组合：目标文件名取字节 + 目录项判定（核心，逐条对照 fat32_reference.py）
    //
    //   项内偏移 <-> 字段（FAT32 规范 + reference 一致）：
    //     0~7    名字 8 字节      8~10   扩展名 3 字节
    //     11     属性             20~21  FstClusHI
    //     26~27  FstClusLO        28~31  文件大小
    //-------------------------------------------------------------------------
    always @(*) begin
        cur = i_data;

        // 目标文件名在当前字母位置上的字节。
        //   刻意用 case 而不是 target_name[bcnt[2:0]*8 +: 8]：
        //     1) 位选下标带乘法正是"上下文宽度陷阱"的温床；
        //     2) 那样索引只能在 0~7 里循环，第 8/9/10 个字节永远比不上，
        //        扩展名 BMP/WAV 就永远匹配不上（早期版本踩过这个真 bug）。
        case (bcnt[3:0])
        4'd0:  tf_byte = target_name[87:80];   // 名字第 1 字节
        4'd1:  tf_byte = target_name[79:72];   // 名字第 2 字节
        4'd2:  tf_byte = target_name[71:64];   // 名字第 3 字节
        4'd3:  tf_byte = target_name[63:56];   // 名字第 4 字节
        4'd4:  tf_byte = target_name[55:48];   // 名字第 5 字节
        4'd5:  tf_byte = target_name[47:40];   // 名字第 6 字节
        4'd6:  tf_byte = target_name[39:32];   // 名字第 7 字节
        4'd7:  tf_byte = target_name[31:24];   // 名字第 8 字节
        4'd8:  tf_byte = target_name[23:16];   // 扩展名第 1 字节
        4'd9:  tf_byte = target_name[15:8];    // 扩展名第 2 字节
        4'd10: tf_byte = target_name[7:0];     // 扩展名第 3 字节
        default: tf_byte = 8'h00;
        endcase

        // "活着的目录项"：首字节既不是结束项 00、也不是已删除 E5。
        // 必须是组合判断：偏移 0 那拍 name_wr / match_acc 就要成立，
        // 此刻"本项首字节"就是 cur，直接判它最快也最准
        ent_ok = (bcnt[4:0] == 5'd0)
                 ? ((cur != 8'h00) && (cur != 8'hE5))
                 : ((fst0 != 8'h00) && (fst0 != 8'hE5));

        // 属性字节必须取本目录项的，所以偏移 11 那一拍直接用 cur
        //   踩过的坑（真实卡才暴露）：att_q 是寄存器，偏移 11 那一拍写进去、
        //   偏移 12 才看得见。而 rec_commit 恰好就在偏移 11 判定，如果这里用
        //   att_q，判的就是上一条目录项的属性 —— 整个"本项是不是文件"的
        //   判定整整错位一条。合成镜像上所有目录项属性都是 0x20，错位恰好看不
        //   出来；真实卡上 00_1.BMP 前面正好是一条已删除的 SYSTEM~1（属性 0x16
        //   含目录位），于是 00_1.BMP 被当成"目录"丢掉，而紧跟 03_4.BMP 的
        //   LFN 槽位（前一条属性 0x20）反而被当成文件写进表里。
        //   偏移 >= 12 时 att_q 就是本项属性，直接用它（b2x 捕获用得到）。
        att_eff = (bcnt[4:0] == 5'd11) ? cur : att_q;

        // "要记录到文件表的文件"：
        // 必须限定在"解析根目录"期间（rsec==2）
        //   MBR/DBR 那两扇区里也有一堆看起来像目录项的字节（BPB、分区表），
        //   不加这个限定就会在表里混进若干垃圾条目 —— 仿真里实测混进了 4 条。
        //   下面这些条件与 fat32_reference.py 的 kind 判定完全一致：
        //   属性含 0x10（目录位：. / .. / 子目录）     -> 不是
        //   属性含 0x08（卷标）                        -> 不是
        //   属性 0F（长文件名槽位）                    -> 不是
        //   首字节 00（结束项）/ E5（已删除）           -> 不是（ent_ok=0）
        //   剩下 (attr & 0x18)==0 的短目录项才是文件（本卡上 attr 都是 0x20）
        //
        // LFN 槽位就是靠"属性 == 0x0F"认出来的
        //   规范里 LFN 槽位的属性字节恒为 0x0F，所以判属性字节就够了，不需要
        //   另设"LFN 序列进行中"的状态机（老版本用首字节 == 0x0F 去触发，
        //   那是错的：LFN 槽位的首字节是序号 0x01~0x14 / 0x41~0x54，永远不是
        //   0x0F；反倒是一个序号为 15 的长名槽位会误触发，把紧随其后的真文件
        //   当成 LFN 丢掉）。
        rec_ok = dir_mode && ent_ok && (att_eff != 8'h0F) &&
                 ((att_eff & 8'h18) == 8'h00);

        // 名字左移进 nm_buf：项内偏移 0~10 的每一拍都要写。
        // 只依赖组合的 ent_ok 与偏移范围，绝不用 att_q
        name_wr = dir_mode && ent_ok && (bcnt[4:0] <= 5'd10);

        // ---- 本拍要不要"提交一条记录" ----
        // 为什么把真正的写表放在"下一个目录项的偏移 0"
        //   一条目录项的字段是分几拍才收齐的，而寄存器要下一拍才更新：
        //     偏移 11：属性 -> att_q、rec_ok 落定
        //     偏移 20/21：FstClusHI 落定
        //     偏移 26/27：FstClusLO 落定
        //     偏移 28..31：大小四字节落定（偏移 31 只落下最后一个字节）
        //   如果在偏移 27 就写首簇、偏移 31 就写大小，读到的还是上一拍的
        //   旧值】—— 仿真里整张表的首簇号正好错位一整项，就是这么来的。
        //   改到"下一个目录项的偏移 0"写：这时本项所有字段都已稳定，
        //   而且 nm_buf / b2x 还没被新项覆盖，一次写完，零歧义。
        //     * rec_commit：偏移 11 判断出"本项是有效文件"，立 pend_rec
        //     * rec_write ：偏移 0 且 pend_rec 还立着 -> 真正写表
        rec_commit = rec_ok && (bcnt[4:0] == 5'd11);
        rec_write  = pend_rec && (bcnt[4:0] == 5'd0);
    end

    //-------------------------------------------------------------------------
    // 组合：名字匹配累积器（单独一个 always，不要塞进 task）
    //   match_acc = "偏移 0 一路比到当前偏移，每个字节都相等"
    //     * 偏移 0：由首字节比较结果置初值（不管这个字节是哪种目录项，
    //               先无条件比较，能不能算数由后面的 rec_ok 决定）
    //     * 偏移 1~10：与当前字节比较结果做 AND 累积
    //     * 偏移 0 的清零优先级最高（写在最后，同一寄存器后写的生效）
    //
    // 为什么不能拿 rec_ok 当门控
    //   rec_ok 依赖 att_q，而 att_q 要到偏移 11 才是本项的值。
    //   用 rec_ok 门控会让偏移 0 没有初值，累积器永远停在 0。
    //
    // 为什么单独拉出来写
    //   塞在 task 里时，"偏移 0 置初值"和"偏移 0 清 stick"挤在同一个块里，
    //   顺序稍有闪失就会被清零覆盖（本模块真踩过：match_acc 恒为 0）。
    //   单独一个 always、把顺序写死，就不会再出这种问题。
    //-------------------------------------------------------------------------
    always @(*) begin
        if (bcnt[4:0] == 5'd0)
            acc_nx = (cur == tf_byte);
        else if (bcnt[4:0] <= 5'd10)
            acc_nx = match_acc && (cur == tf_byte);
        else
            acc_nx = match_acc;
    end

    //=========================================================================
    // task：解析"当前正在处理的那个字节"（偏移 = off）
    //
    //   写成 task 是为了让 S_REQ（偏移 0）和 S_READ（偏移 1..511）共用同一套
    //   解析代码 —— 早期两处分头写，偏移 0 被处理两次/漏一次，名字首字符
    //   永远进不了 nm_buf。
    //
    //   本 task 只做寄存器赋值，内部没有延时/事件控制，TD 与 iverilog 都能
    //   正常内联展开，是可综合的写法。
    //
    //   注意：match_acc 与 stick 的置位/清零不在这里做，
    //   它们各有独立的 always 块（见上面"名字匹配累积器"与下面"sticky 锁存"），
    //   免得和这里的其它赋值抢同一个寄存器、顺序出错。
    //=========================================================================
    task cur_byte;
        input [9:0] off;                     // 当前字节在扇区内的偏移
        begin
            // ---- 0) 偏移 0：锁首字节、判结束项 ----
            //   注意：stick 的置位/清零不在这里做，它在下面那个独立的
            //   "sticky 锁存"always 块里（避免同一个 reg 出现在两个 always 块里，
            //   verilog_lint.py 会报"同一 reg 在多个 always 块赋值"，综合器也不认）。
            if (off[4:0] == 5'd0) begin
                fst0   <= cur;
                end_q  <= (cur == 8'h00);        // 00 是结束项，本扇区到此为止
                // 这里不做 LFN 判定：LFN 槽位是靠偏移 11 的属性字节
                // == 0x0F 认出来的（见 rec_ok 的说明），首字节是序号不是 0x0F。
            end

            // ---- 1) 名字 11 字节：偏移 0~10，逐字节收进 nm_buf ----
            // 位选下标必须是常量，所以这里只能用移位/拼接，不能写
            // nm_buf[(10-off)*8 +: 8]（Icarus 直接报 "Malformed statement"）
            //
            // 拼接的位宽必须写对
            //     nm_buf 是 88 位 = 11 字节，约定 byte0 在最高8 位。
            //       偏移 0 ：byte0 <= cur，高 8 位直接赋值，其余保持
            //       偏移 k ：byte0..9 左移一位（[79:0]），cur 补到 byte10
            //     早期写成 {nm_buf[79:0], cur}（88 位）：左移一次就把 byte0
            //     挤出 88 位之外，名字少一个字符（01.BMP 变成 00 31 20 ...）。
            //     正确写法是拼 nm_buf[79:0] 这一半，丢掉的是本来就为 0 的 byte10。
            //
            // 0x05 是规范里的转义：目录项首字节为 0x05 表示原始文件名
            //       首字符是 0xE5（真实存在的字符）。fat32_reference.py 的
            //       decode_short_name() 做同样的还原，这里保持一致。
            if (name_wr) begin
                if (off[4:0] == 5'd0)
                    nm_buf[87:80] <= (cur == 8'h05) ? 8'hE5 : cur;
                else
                    nm_buf <= {nm_buf[87:80], nm_buf[71:0], cur};
            end

            // ---- 2) 偏移 11 = 属性字节 ----
            //   原样存下来；是不是 LFN 槽位、是不是目录/卷标，统一由 rec_ok 判。
            if (off[4:0] == 5'd11)
                att_q <= cur;

            // ---- 5) 32 位字段的字节对 ----
            //     rec_ok 为假时（LFN/目录/卷标/已删除）不收，避免把 LFN 槽位里
            //     的校验和字节误当 FstClusHI 用。
            if (rec_ok) begin
                case (off[4:0])
                5'd20:   b20 <= cur;             // FstClusHI 低字节
                5'd21:   b21 <= cur;             // FstClusHI 高字节
                5'd26:   b26 <= cur;             // FstClusLO 低字节
                5'd27:   b27 <= cur;             // FstClusLO 高字节
                5'd28:   b28 <= cur;             // 大小 bit  7:0
                5'd29:   b29 <= cur;
                5'd30:   b30 <= cur;
                5'd31:   b31 <= cur;
                default: ;                       // 其余偏移本模块不关心
                endcase
            end

            // ---- 5) 立"本项是有效文件"的标记；真正的写表在偏移 0 ----
            if (rec_commit) begin
                if (rec_idx == TBL_LAST[3:0])
                    err_code <= ERR_OVF;         // 表满：报错，不再往下写
                else
                    pend_rec <= 1'b1;
            end

            // ---- 5b) 下一个目录项的偏移 0：一次把上一条记录完整写进表 ----
            //   此刻 nm_buf / b2x / att_q 都还是上一项的最终值，不会被新项污染。
            if (rec_write) begin
                tbl_name[rec_idx]    <= nm_buf;
                // 约束 2：首簇 = {FstClusHI, FstClusLO}，32 位一起拼
                tbl_cluster[rec_idx] <= {b21, b20, b27, b26};
                tbl_size[rec_idx]    <= {b31, b30, b29, b28};
                tbl_attr[rec_idx]    <= att_q;
            end

            // ---- 6) 新目录项开始：清掉"本项是有效文件"的标记 ----
            //     写在最后：保证偏移 11 立的标记不会被同拍误清
            //     （偏移 11 与偏移 0 不会同拍，这里只是把优先级写明确）。
            if (off[4:0] == 5'd0)
                pend_rec <= 1'b0;

            // ---- 7) MBR 分区表项 / BPB 字段 / 两个签名 ----
            if (rsec == 2'd0) begin
                // 分区表第 0 项：偏移 446 起，+4 类型，+8 起始 LBA，+12 扇区数
                if ((off >= 10'd450) && (off <= 10'd453))
                    part_type[({8'd0, off} - 10'd450) * 8 +: 8] <= cur;
                if ((off >= 10'd454) && (off <= 10'd457))
                    part_start[({8'd0, off} - 10'd454) * 8 +: 8] <= cur;
                if ((off >= 10'd458) && (off <= 10'd461))
                    part_sectors[({8'd0, off} - 10'd458) * 8 +: 8] <= cur;
                if (off == 10'd510) mbr_b510 <= cur;
                if (off == 10'd511) mbr_b511 <= cur;
            end else if (rsec == 2'd1) begin
                // BPB 字段（与 fat32_reference.py 的 parse_bpb 一一对应）
                if (off == 10'd11) bps[7:0]   <= cur;
                if (off == 10'd12) bps[15:8]  <= cur;
                if (off == 10'd13) spc        <= cur;
                if (off == 10'd14) rsvd[7:0]  <= cur;
                if (off == 10'd15) rsvd[15:8] <= cur;
                if (off == 10'd16) nfat       <= cur;
                if (off == 10'd17) root_ent[7:0]  <= cur;
                if (off == 10'd18) root_ent[15:8] <= cur;
                if (off == 10'd28) fatsz16[7:0]   <= cur;
                if (off == 10'd29) fatsz16[15:8]  <= cur;
                if (off == 10'd36) fatsz32[7:0]   <= cur;
                if (off == 10'd37) fatsz32[15:8]  <= cur;
                if (off == 10'd38) fatsz32[23:16] <= cur;
                if (off == 10'd39) fatsz32[31:24] <= cur;
                if (off == 10'd44) root_clus[7:0]   <= cur;
                if (off == 10'd45) root_clus[15:8]  <= cur;
                if (off == 10'd46) root_clus[23:16] <= cur;
                if (off == 10'd47) root_clus[31:24] <= cur;
                if (off == 10'd510) dbr_b510 <= cur;
                if (off == 10'd511) dbr_b511 <= cur;
            end
        end
    endtask

    //-------------------------------------------------------------------------
    // 组合：本扇区的校验结果（在 S_CHK 里用）
    //
    // 为什么校验不能和"收最后一字节"放在同一拍
    //   MBR/DBR 的最后一个签名字节是在 S_READ 最后一拍才写进寄存器的
    //   （非阻塞赋值）。同一拍就判 !mbr_sig_ok，读到的是旧值 0，
    //   正确的签名也会被误报成 ERR_MBR_SIG。多隔一拍（S_CHK）最省事也最可靠。
    //-------------------------------------------------------------------------
    reg        chk_ok;
    reg [3:0]  chk_err;

    always @(*) begin
        chk_ok  = 1'b1;
        chk_err = ERR_NONE;

        if (rsec == 2'd0) begin
            // ---- MBR：查签名 + 分区项类型 ----
            if (!mbr_sig_ok) begin
                chk_ok  = 1'b0;
                chk_err = ERR_MBR_SIG;
            end else if (part_type == 8'h00) begin
                chk_ok  = 1'b0;
                chk_err = ERR_PART_EMPTY;
            end
        end else if (rsec == 2'd1) begin
            // ---- DBR：查签名 + BPB 关键字段 ----
            if (!dbr_sig_ok) begin
                chk_ok = 1'b0; chk_err = ERR_DBR_SIG;
            end else if (bps != 16'd512) begin
                chk_ok = 1'b0; chk_err = ERR_BPS;
            end else if (!spc_ok) begin
                chk_ok = 1'b0; chk_err = ERR_SPC;
            end else if (root_ent != 16'd0) begin
                chk_ok = 1'b0; chk_err = ERR_ROOTENT;
            end else if ((fatsz32 == 32'd0) && (fatsz16 == 16'd0)) begin
                chk_ok = 1'b0; chk_err = ERR_FATSZ;
            end else if (root_clus < 32'd2) begin
                chk_ok = 1'b0; chk_err = ERR_ROOTCLU;
            end else if (lba_range_bad) begin
                chk_ok = 1'b0; chk_err = ERR_LBA_RANGE;
            end
        end else begin
            // ---- 根目录一个扇区收完 ----
            if (!end_q && ((rsec_cnt + 32'd1) >= {24'd0, spc})) begin
                // 本簇读完仍未见 00 结束项。规范做法是查 FAT 跟根目录自己的
                // 簇链；本镜像 root_chain=[2] 且 FAT[2]=0x0FFFFFFF（EOC），
                // 一个簇就结束。这里不猜：报明确错误停下，避免把别的数据
                // 当目录项解析出一堆垃圾文件（假阳性比缺文件更危险）。
                chk_ok = 1'b0; chk_err = ERR_CHAIN_LEN;
            end
        end
    end

    //-------------------------------------------------------------------------
    // 时序：名字匹配累积器 match_acc
    //   偏移 0 -> 由首字节比较结果置初值
    //   偏移 1~10 -> 与当前字节比较结果做 AND
    //   其余偏移 -> 保持
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            match_acc <= 1'b0;
        else if (st == S_IDLE)
            match_acc <= 1'b0;
        else if (cur_rd_valid)
            match_acc <= acc_nx;
    end

    //-------------------------------------------------------------------------
    // 时序：文件表的写入下标 rec_idx
    //   一条记录分三拍写（偏移 11 写名字、27 写首簇、31 写大小），
    //   三拍必须落到同一个下标上；写完（偏移 31）才 +1。
    //   所以下标不能直接用 o_count（那条记录还没写完时它不该动），
    //   而是单独一个 rec_idx：偏移 31 写完才推进。
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            rec_idx <= 4'd0;
        else if (st == S_IDLE)
            rec_idx <= 4'd0;
        else if (cur_rd_valid && rec_write) begin
            if (rec_idx == TBL_LAST[3:0])
                rec_idx <= TBL_LAST[3:0];        // 表满，停住
            else
                rec_idx <= rec_idx + 4'd1;
        end
    end

    //-------------------------------------------------------------------------
    // 时序：对外可见的文件条数 o_count
    //   与 rec_idx 同步推进，但表满时不再增加（ERR_OVF 已报出）。
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            o_count <= 5'd0;
        else if (st == S_IDLE)
            o_count <= 5'd0;
        else if (cur_rd_valid && rec_write) begin
            if (o_count == TBL_LAST)
                o_count <= TBL_LAST;
            else
                o_count <= o_count + 5'd1;
        end
    end

    //-------------------------------------------------------------------------
    // 时序： 约束 1 的 sticky 锁存 stick
    //   置位：项内偏移 10（第 11 个名字字节）且 11 个字节全中
    //   清零：只有下一个目录项的首字节（项内偏移 0）
    //   其它时候一律保持 —— 同一扇区里后面那些等长名字的失配碰不到它。
    //   这正是参考设计 sd_file_reader.v 用瞬时 file_found 时丢掉的那一步。
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            stick <= 1'b0;
        else if (st == S_IDLE)
            stick <= 1'b0;
        else if (cur_rd_valid) begin
            if (bcnt[4:0] == 5'd0)
                stick <= 1'b0;                        // 新目录项开始
            else if ((bcnt[4:0] == 5'd10) && match_acc && (cur == tf_byte))
                stick <= 1'b1;                        // 11 字节全中，粘住
        end
    end

    //-------------------------------------------------------------------------
    // 时序：本扇区"正在处理第 bcnt 号偏移"时 cur_rd_valid=1
    //   S_REQ 收到第一个字节（偏移 0）与 S_READ 的每一拍都算。
    //   注意 S_READ 里 bcnt==512 时不再收，避免把下一扇区的字节算进来。
    //-------------------------------------------------------------------------
    assign cur_rd_valid = ((st == S_REQ) && i_data_valid) ||
                          ((st == S_READ) && i_data_valid && (bcnt <= 10'd511));

    //-------------------------------------------------------------------------
    // 临时诊断 时序：本次解析一共收了多少个数据字节dbg_rx_bytes
    //
    //   为什么这个计数最有用：
    //     正常一次解析 = 扇区数 x 512（真卡上 6 个扇区 = 0xC00 = 3072）。
    //     只要它不是 512 的整数倍，就说明数据通路丢字节/多字节——
    //     "每个扇区丢第一个字节（DATA_LEAD 那一类）"会精确地表现成
    //     511 * 扇区数；"收到一整段空白"则表现成 512 * 扇区数但内容全 0。
    //     这两者的区分只能靠 dbg_root_b0 / dbg_rx_bytes 一起看。
    //
    // 本块是 dbg_rx_bytes 的唯一驱动（复位也在这里，主状态机那个
    //     always 块里不要再出现这个名字，否则 TD 报 HDL-8007 多驱动）
    //   计数条件用 cur_rd_valid：与实际送进 cur_byte 解析的字节完全同一批。
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            dbg_rx_bytes <= 16'd0;
        else if (st == S_IDLE)
            dbg_rx_bytes <= 16'd0;
        else if (cur_rd_valid)
            dbg_rx_bytes <= dbg_rx_bytes + 16'd1;
    end

    //-------------------------------------------------------------------------
    // 主状态机
    //-------------------------------------------------------------------------
    integer k;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            st           <= S_IDLE;
            rsec         <= 2'd0;
            rsec_cnt     <= 32'd0;
            err_code     <= ERR_NONE;
            // o_count 和 rec_idx 不在这里复位
            //   它们各自有专属的 always 块负责复位（那些块自带
            //   !rst_n 与 st==S_IDLE 分支），本块再赋值就是多驱动。
            //   iverilog 允许多驱动、两个块赋相同的值结果也对，所以
            //   仿真能全 PASS；但 TD 会直接报
            //     HDL-8007 net 'o_count[4]' is constantly driven
            //     from multiple places
            //   而拒绝综合。与下面 stick 的处理是同一个道理。
            //   同理，match_acc 也不在这里复位（下面那句已删）：它由
            //   "名字匹配累积器 match_acc"那个专属 always 块独占驱动，
            //   那个块自带 !rst_n 与 st==S_IDLE 分支，赋值完全相同。
            // 这一处是第一轮手工修复时漏掉的：只删了 o_count/rec_idx，
            //     match_acc 在本块的复位分支和本块的 S_IDLE 分支
            //     各还留着一句，和它的专属块凑成两处驱动 —— TD 照样报
            //     HDL-8007。检查工具：tools/verilog_multidriver_check.py。
            bcnt         <= 10'd0;
            tmo_cnt      <= 32'd0;
            tmo_all_cnt  <= 32'd0;
            fst0         <= 8'h00;
            att_q        <= 8'h00;
            end_q        <= 1'b0;
            pend_rec     <= 1'b0;
            nm_buf       <= 88'd0;
            // 注意：stick 不在这里复位 —— 它由专门的"sticky 锁存"always 块
            //   独占驱动（那个块自带异步复位）。同一个 reg 出现在两个 always
            //   块里会被 verilog_lint.py 判为多驱动，综合器也不接受。
            b20 <= 8'd0; b21 <= 8'd0;
            b26 <= 8'd0; b27 <= 8'd0;
            b28 <= 8'd0; b29 <= 8'd0; b30 <= 8'd0; b31 <= 8'd0;
            bps          <= 16'd0;
            spc          <= 8'd0;
            rsvd         <= 16'd0;
            nfat         <= 8'd0;
            root_ent     <= 16'd0;
            fatsz32      <= 32'd0;
            fatsz16      <= 16'd0;
            root_clus    <= 32'd0;
            part_lba     <= 32'd0;
            fat_lba      <= 32'd0;
            data_lba     <= 32'd0;
            root_base    <= 32'd0;
            part_type    <= 8'd0;
            part_start   <= 32'd0;
            part_sectors <= 32'd0;
            mbr_b510     <= 8'd0;
            mbr_b511     <= 8'd0;
            dbr_b510     <= 8'd0;
            dbr_b511     <= 8'd0;
            dbg_part_lba <= 32'd0;
            dbg_data_lba <= 32'd0;
            dbg_root_lba <= 32'd0;
            dbg_fat_lba  <= 32'd0;
            dbg_secs     <= 16'd0;
            dbg_part_type<= 8'd0;
            // 临时诊断：本块是这两个 reg 的唯一驱动（见它们的锁存处）
            dbg_root_b0  <= 8'h00;
            dbg_root_b1  <= 8'h00;
            // 复位整张表。循环上界必须跟着 MAX_FILES 走 ——
            //   写死 16 会在表深度降成 10 之后触发
            //   HDL-8007 index 10 is out of range [0:9]，TD 直接把本模块
            //   降级成黑盒（实测踩过）。
            for (k = 0; k < MAX_FILES; k = k + 1) begin
                tbl_name[k]    <= 88'd0;
                tbl_cluster[k] <= 32'd0;
                tbl_size[k]    <= 32'd0;
                tbl_attr[k]    <= 8'd0;
            end
        end else begin
            // ---- 超时计数（2026-10 修复：排队时间不计入传输超时） ----
            //   只在"等扇区数据"的两个状态（S_REQ 收第一个字节 / S_READ 收后续）
            //   里动；其余状态一律清零（换扇区时从头算）。
            //     * 收到数据字节      -> 两个计数器都清零
            //     * 没收到数据：
            //         tmo_cnt     : 只有已被仲裁器授权(i_granted=1) 才加
            //                       —— 排队等卡的时间不算传输超时
            //         tmo_all_cnt : 不看授权，一直加 —— 防"永远排不上队"的兜底
            //   两个计数器都饱和在各自的阈值上（不再 +1），避免无谓翻位。
            // 这两个 reg 只在本块里被赋值（含复位），没有第二个驱动源
            if ((st == S_REQ) || (st == S_READ)) begin
                if (i_data_valid) begin
                    tmo_cnt     <= 32'd0;
                    tmo_all_cnt <= 32'd0;
                end else begin
                    if (i_granted && (tmo_cnt < TO_LIMIT))
                        tmo_cnt <= tmo_cnt + 32'd1;
                    if (tmo_all_cnt < TO_LIMIT_ALL)
                        tmo_all_cnt <= tmo_all_cnt + 32'd1;
                end
            end else begin
                tmo_cnt     <= 32'd0;
                tmo_all_cnt <= 32'd0;
            end

            case (st)
            //============================================================ 空闲
            S_IDLE: begin
                rsec      <= 2'd0;
                rsec_cnt  <= 32'd0;
                err_code  <= ERR_NONE;
                bcnt      <= 10'd0;
                end_q     <= 1'b0;
                // match_acc 不在这里清 —— 它的专属 always 块里已有
                //   else if (st == S_IDLE) match_acc <= 1'b0;
                // 本块再赋一次就是同一个 reg 两处驱动（TD HDL-8007）。
                pend_rec  <= 1'b0;
                dbg_secs  <= 16'd0;
                if (start) begin
                    if (tgt_we)
                        target_name <= tgt_name;
                    st <= S_REQ;
                end
            end

            //============================================================ 请求 / 收第一个字节
            S_REQ: begin
                if (i_data_valid) begin
                    // 临时诊断：根目录首扇区的第 1 个字节
                    //   真卡上这个字节应该是 0xE5（首项是一条已删除的 LFN 槽位），
                    //   既不是 0x00（会被当成目录结束 -> count=0、err=0，正是板上的现象）
                    //   也不是 0x30（那是合成镜像的根目录首项 00_1.BMP）。
                    //   只在这个条件成立的那一拍锁存，别的扇区/别的偏移都不碰它。
                    if ((rsec == 2'd2) && (rsec_cnt == 32'd0))
                        dbg_root_b0 <= i_data;

                    // 偏移 0：新目录项开始，也是 stick 唯一被清零的地方
                    cur_byte(10'd0);
                    dbg_secs <= dbg_secs + 16'd1;
                    bcnt     <= 10'd1;
                    st       <= S_READ;
                end else if (tmo_hit) begin
                    err_code <= ERR_SECTOR_TO;
                    st       <= S_DONE;
                end
            end

            //============================================================ 收扇区 + 边收边解析
            S_READ: begin
                if (i_data_valid) begin
                    // 临时诊断：根目录首扇区的第 2 个字节（偏移 1）
                    //   与 dbg_root_b0 拼成 "E5 20" 就是"确实落在 LBA 0xA000"
                    //   的指纹；若得到 "E5 00" / "00 00" 之类，说明数据通路有问题。
                    if ((rsec == 2'd2) && (rsec_cnt == 32'd0) && (bcnt == 10'd1))
                        dbg_root_b1 <= i_data;

                    cur_byte(bcnt);          // 解析当前偏移

                    if (bcnt == 10'd511) begin
                        // 扇区末字节处理完 -> 去 S_CHK 校验并决定下一个扇区
                        bcnt <= 10'd0;
                        st   <= S_CHK;
                    end else begin
                        bcnt <= bcnt + 10'd1;
                    end
                end else if (tmo_hit) begin
                    // 收到一半断了：同样报超时，不要静默等下去
                    err_code <= ERR_SECTOR_TO;
                    st       <= S_DONE;
                end
            end

            //============================================================ 校验并锁存下一段参数
            S_CHK: begin
                if (!chk_ok) begin
                    err_code <= chk_err;
                    st       <= S_DONE;
                end else if (rsec == 2'd0) begin
                    // MBR 收完：锁存分区起始 LBA/类型，准备去读 DBR。
                    //   part_start 是上一拍才由 MBR 最后几个字节写进来的，
                    //   所以必须在这里（而不是更早）锁存。
                    part_lba      <= part_start;
                    dbg_part_lba  <= part_start;
                    dbg_part_type <= part_type;
                    rsec          <= 2'd1;
                    rsec_cnt      <= 32'd0;
                    st            <= S_SET;
                end else if (rsec == 2'd1) begin
                    // DBR 收完：数据区/FAT/根目录的绝对扇区落地。
                    //   用组合的 root_base_x，因为 root_base 寄存器本拍才写。
                    fat_lba      <= fat_base_x[31:0];
                    data_lba     <= data_base_x[31:0];
                    root_base    <= root_base_x[31:0];
                    dbg_fat_lba  <= fat_base_x[31:0];
                    dbg_data_lba <= data_base_x[31:0];
                    dbg_root_lba <= root_base_x[31:0];
                    rsec         <= 2'd2;
                    rsec_cnt     <= 32'd0;
                    st           <= S_SET;
                end else if (end_q) begin
                    // 根目录遇到 0x00 结束项：解析完毕
                    st <= S_DONE;
                end else begin
                    // 同簇下一个扇区
                    rsec_cnt <= rsec_cnt + 32'd1;
                    st       <= S_REQ;
                end
            end

            //============================================================ 等参数落定一拍
            // 这一拍是必需的，不是凑数（见文件头要点 B）
            //   o_rd_lba 是纯组合：rsec==2 时要读 root_base + rsec_cnt，
            //   而 root_base 是在 S_CHK 那一拍才写进去的（非阻塞赋值）。
            //   若从 S_CHK 直接跳 S_REQ，S_REQ 第一拍的 o_rd_lba 还是旧值 0，
            //   仿真里就表现成"请求读根目录，实际去读了扇区 0"。
            //   同理适用于 rsec 由 0 变 1 时 part_lba 的锁存。
            S_SET: begin
                st <= S_REQ;
            end

            //============================================================ 收尾
            S_DONE: begin
                st <= S_DONE;
            end

            default: st <= S_IDLE;
            endcase
        end
    end

endmodule
