//=============================================================================
// 文件名  : video_enhance.v
// 功能    : 视频 RGB 通路亮度调节（乘法式 + 高光软膝）
//
// 为什么最终选乘法式
// --------------------
//   数学上，三种亮度实现里只有纯乘法能精确保持色相和饱和度：
//
//     操作                                色相   饱和度
//     out = in + k        (加偏移)         变     变      <- 暗通道被截断
//     out = in + a*in*(255-in)/256 (曲线)  微变   变      <- 逐通道提中间调
//     out = in * k        (乘法)         不变   不变    <- 只有它精确保持
//
//   直观例子（粉色 255,128,128，提亮到同样亮度）：
//       加偏移     -> (255,191,191)  饱和度暴跌，看上去"泛白"
//       曲线       -> (255,191,191)  同样饱和度暴跌
//       乘法 1.4x  -> (357,179,179) -> 软膝后 (255,179,179)
//                     比例 R:G:B 保持不变 -> 色相与饱和度都不变
//
//   所以"泛白/泛黑"的根因不是削顶，而是逐通道非线性操作改变了饱和度。
//
// 高光软膝
// --------
//   乘法的唯一副作用是超过 255 会被硬削成白。这里不硬削，而是：
//       超过 KNEE 的部分只保留 1/4
//           w > KNEE :  out = KNEE + (w - KNEE)/4
//   这样高光平滑收敛，仍然单调、不出现大片死白，
//   而且本工程的亮度上限 1.40x 时最多只溢出 2 个数值（255->257->255）。
//
//   软膝是逐通道的，因此极亮的像素会有轻微去饱和 —— 这是所有
//   非线性色调映射的共性，但只在接近纯白处才发生，肉眼不可辨。
//
// 参数
// ----
//   I_gain：组合增益 Q7 = 对比度kc × 亮度kb / 128
//   I_offb：偏移 O 的偏置形式（真值 = I_offb - 128），O = kb - G
//
//   完整算法（三通道相同）：
//       out = clamp( knee( in*G/128 + O ) )
//   两段式对比度（2026-10-30 二次修正）：
//       kc >= 1.0（增强）：O = kb - G，绕 128 旋转，压暗部 + 提亮部
//       kc <  1.0（减弱）：O = 0     ，纯增益保黑，只压白点
//       为什么减弱段必须 O=0：正偏移会把黑位和饱和度一起毁掉（实测饱和度
//       -42%、黑底变灰），详见 osd_ctrl.v 里"降低对比度时必须保黑"。
//   为什么 O = kb - G 而不是 128-G（增强段）：
//       只调亮度时 kc=1 => G=kb => O=0，画面等比缩放（中点跟着变亮/变暗），
//       这才是"亮度"。若写成 128-G，亮度旋钮会变成绕 128 的对比度，中点不动。
//   为什么膝在偏移之后：
//       膝点是输出域的 224；偏移为负时若先膝后偏移，膝点对应不到输出域 224，
//       高光会被额外压暗。
//   中点性质：
//       增强段 out(128) = 128*kb（中点不随对比度动）
//       减弱段 out(128) = 128*G/128（纯缩放，中点跟着增益一起降）
//
// 为什么不用 signed / function，以及位宽
// -------------------------------------
//   工具链对 signed 兼容性不佳；function 内部 reg 共享、多次调用不可靠。
//   位宽一律显式写死，避免"上下文决定宽度"把乘积截断（踩过两次坑）。
//       in * gain           : 8+8 = 16 位 -> 中间信号必须显式 16 位
//       (in*gain) >> 7      : 结果最大 508 -> 必须 9 位，用 w[8:0] 接
//=============================================================================

module video_enhance (
    input               I_clk,
    input               I_rst,

    // ---- 视频输入 ----
    input      [23:0]   I_rgb,
    input               I_vs,
    input               I_de,

    // ---- 组合增益（Q7，128 = 1.0x）----
    //   I_gain = 对比度C × 亮度B / 128，两旋钮相乘后送进来
    input      [7:0]    I_gain,

    // ---- 对比度偏移（偏置 128 表示 0）----
    //   真值 = I_offb - 128，实际只在 79~128 之间（对应 -49~0）
    //   ★ 永远不为正：降低对比度那一段上层给的是恒定 128（保黑），
    //     理由见 osd_ctrl.v 里"降低对比度时必须保黑"那一节。
    //   为什么偏置而不是有符号：本模块三通道都要做加法+饱和，
    //   无符号偏置可以用同一条无符号比较链，省掉符号扩展与有符号比较器。
    //
    //   数学来源：对比度增强 = 绕 128 旋转
    //       out = (in-128)*G/128 + 128 = in*G/128 + (128-G)
    //   前一项就是下面已有的乘法，后一项就是这里的偏移。
    //   I_offb = (128-G) + 128 = 256-G，所以恒为正，8 位装得下。
    input      [7:0]    I_offb,

    // ---- 高光肩起点（输出域，0~255）----
    //   增益 <= 1.0x 时上层给 255（= 不压，中性必须直通）；
    //   增益 > 1.0x 时随增益下降，把"会溢出 255 的那一段"折进 255 以内，
    //   保住高光层次而不是硬削平。由 osd_ctrl 按当前增益算好，逐像素不再算。
    input      [7:0]    I_knee,

    // ---- 视频输出（比输入晚 1 拍）----
    output reg [23:0]   O_rgb,
    output reg          O_vs,
    output reg          O_de
);

    // 软膝（高光肩）：膝点在"输出域"由 I_knee 给出，斜率降到 1/4。
    //   偏置域里输出 x 对应 x+128。
    //   ★ 膝必须放在加偏移之后：偏移为负时若先把膝点定在乘法输出域，
    //     高光会被额外压暗（实测 in=255、对比度1.3x 时算出 212 而非 255）。
    //   ★ 膝点必须随增益变：固定 224 时，增益 1.0x（中性）也会把
    //     255 压成 231 —— 白色不是白色，不符显示器"中性直通"的常识。
    wire [9:0] KNEE_B = {2'b00, I_knee} + 10'd128;

    wire [7:0] r_in = I_rgb[23:16];
    wire [7:0] g_in = I_rgb[15:8];
    wire [7:0] b_in = I_rgb[7:0];

    //-------------------------------------------------------------------------
    // R 通道
    //-------------------------------------------------------------------------
    wire [15:0] mp_r = r_in * I_gain;                 // 8*8 = 16 位
    wire [9:0]  p_r  = mp_r[15:7];                    // in*G/128，0..500
    wire [9:0]  b_r  = p_r + {2'b00, I_offb};         // 偏置域输出 = out+128
    wire [9:0]  t_r  = (b_r > KNEE_B) ? (KNEE_B + ((b_r - KNEE_B) >> 2)) : b_r;
    wire [9:0]  v_r  = t_r - 10'd128;
    wire [7:0]  ro   = (t_r < 10'd128) ? 8'd0 :
                       (t_r > 10'd383) ? 8'hFF : v_r[7:0];

    //-------------------------------------------------------------------------
    // G 通道
    //-------------------------------------------------------------------------
    wire [15:0] mp_g = g_in * I_gain;
    wire [9:0]  p_g  = mp_g[15:7];
    wire [9:0]  b_g  = p_g + {2'b00, I_offb};
    wire [9:0]  t_g  = (b_g > KNEE_B) ? (KNEE_B + ((b_g - KNEE_B) >> 2)) : b_g;
    wire [9:0]  v_g  = t_g - 10'd128;
    wire [7:0]  go   = (t_g < 10'd128) ? 8'd0 :
                       (t_g > 10'd383) ? 8'hFF : v_g[7:0];

    //-------------------------------------------------------------------------
    // B 通道
    //-------------------------------------------------------------------------
    wire [15:0] mp_b = b_in * I_gain;
    wire [9:0]  p_b  = mp_b[15:7];
    wire [9:0]  b_b  = p_b + {2'b00, I_offb};
    wire [9:0]  t_b  = (b_b > KNEE_B) ? (KNEE_B + ((b_b - KNEE_B) >> 2)) : b_b;
    wire [9:0]  v_b  = t_b - 10'd128;
    wire [7:0]  bo   = (t_b < 10'd128) ? 8'd0 :
                       (t_b > 10'd383) ? 8'hFF : v_b[7:0];

    //-------------------------------------------------------------------------
    // 一级寄存（vs/de 同步延迟同样的拍数）
    //-------------------------------------------------------------------------
    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) begin
            O_rgb <= 24'd0;
            O_vs  <= 1'b0;
            O_de  <= 1'b0;
        end else begin
            O_rgb <= {ro, go, bo};
            O_vs  <= I_vs;
            O_de  <= I_de;
        end
    end

endmodule
