//=============================================================================
// 文件名  : img_scale_2to1.v
// 功能    : 装载侧的定点 2:1 缩小（1280×960 -> 640×480），同时支持 1:1 直通。
//
// 为什么只做 2:1（而不是任意比例）
// --------------------------------
// 本工程当前只需要"一张 1280×960 的图能正确显示"。1280×960 恰好是 640×480 的
// 整数 2 倍，于是缩放退化成"源 2×2 四像素取平均"，只要加法器 + 移位，
// 不需要分数相位、不需要除法器、不需要权重表。
//   代价：只认 1280×960 与 640×480 两档，其他尺寸由 bmp_load_fat 的头校验拒装。
//   收益：LUT ≈ 130（通用面积平均约 450），BRAM 2，DSP 0，slices 影响 +0.7pt。
// 将来要做任意比例时，本模块可原样保留为 2:1 快路径，旁边加通用通路即可。
//
// 算法（严格等于 2×2 均值）
// ------------------------
//   输出(x,y) = ( 源(2x,2y) + 源(2x+1,2y) + 源(2x,2y+1) + 源(2x+1,2y+1) + 2 ) >> 2
//   先横向成对求和（9 bit），偶数行写进行缓冲，奇数行读出来与当前对和相加再 >>2。
//   加 2 再右移 2 是四舍五入；不加法会在整幅图产生 −0.5 的系统性偏暗。
//
// 为什么不需要背压
// ----------------
//   CURL22-27 花屏的根因是"发射器自由跑，FIFO 满了静默丢像素"。
//   本模块的发射**完全由输入驱动**：每 4 个输入像素才产生 1 个输出像素，
//   输出速率永远是输入的 1/4，而写 FIFO 由 125 MHz 侧排空、sd 域只有 62.5 MHz。
//   并且它不产生信箱黑行（黑边在素材里，跟着被平均），不存在"无输入也连发
//   38,400 像素"的通路。所以这里不需要 rdusedw 门控，也不会突刺。
//   ★ 若将来改成"任意比例 + 自动补黑边"，这条结论立即失效，必须补门控。
//
// 与 BMP 存储顺序的关系
// ---------------------
//   BMP 自底向上存储，本模块保持流顺序不变（行对仍然是行对），
//   下游 frame_fifo_write 的 WRITE_V_FLIP 照旧生效：960 行 -> 480 行后
//   翻转仍以整帧为单位，行对不会被拆开。
//=============================================================================

`timescale 1ns / 1ps

module img_scale_2to1 #(
    parameter [11:0] DW = 12'd640,      // 输出宽
    parameter [11:0] DH = 12'd480       // 输出高
)(
    input               I_clk,
    input               I_rst,          // 高有效异步复位（本工程约定）
    input               I_start,        // 单拍：一张新图的像素流开始，清地址
    input               I_2to1,         // 1 = 1280×960 缩小；0 = 640×480 直通
    input      [23:0]   I_pix,
    input               I_de,
    output reg [23:0]   O_pix,
    output reg          O_de
);

    //-------------------------------------------------------------------------
    // 源尺寸（固定 2 倍；改这两组常数就能支持别的 2:1 尺寸，例如 1920×1440）
    //-------------------------------------------------------------------------
    localparam [11:0] SW = DW << 1;     // 1280
    localparam [11:0] SH = DH << 1;     // 960

    //-------------------------------------------------------------------------
    // 行缓冲：640 × 27 bit（3 通道 × 9 bit 对和）
    //   写只在偶数行发生，读只在奇数行发生，同一地址的读写天然错开时间，
    //   所以一块单写+同步读的 RAM 就够（TD 能推断成 BRAM，不是 LUTRAM）。
    //-------------------------------------------------------------------------
    // ★ 必须带这个 TD 专用标注，否则 640×27 会被展开成逻辑（实测 LUT +3,279、
    //   place 阶段 PHY-9009 MSlice 5,169 > 4,900 失败）。
    //   写法照抄 ip/afifo_16_32_256.v 里 TD 自己生成的存储器声明。
    reg  [26:0] line_ram [0:DW-1] ;  /* fehdl force_ram=1, ram_style="bram" */
    reg  [10:0] ram_waddr;
    reg  [26:0] ram_wdata;
    reg         ram_we;
    reg  [10:0] ram_raddr;      // 读地址：必须是寄存器（见下面注释）
    reg  [26:0] ram_q;

    // ★ TD 6.2.1 的 BRAM 推断对这三种写法都**不认**（实测）：
    //     ① 读地址用 wire（assign ram_raddr = x_cnt[11:1]）；
    //     ② 写、读分成两个 always 块；
    //     ③ 地址取位切片直接当下标（line_ram[x_cnt[11:1]]）。
    //   失败表现：640×27 被拆成 17,280 个寄存器 + 大 mux 树，
    //   LUT 15,392 -> 18,671（+3,279），place 阶段报
    //   PHY-9009（MSlice 5,169 > 4,900）直接失败。
    //   能被识别的形状 = "地址先打一拍 → 同步读 → 输出再打一拍"，
    //   与 video_curl 的 geom_mem（640×54，成功进 BRAM）一致。
    //   代价：读通多一级流水，输出流水相应加一级（见下面的 b1/b2）。
    always @(posedge I_clk) begin
        ram_raddr <= x_cnt[11:1];
    end

    always @(posedge I_clk) begin
        if (ram_we) line_ram[ram_waddr] <= ram_wdata;
        ram_q <= line_ram[ram_raddr];
    end

    //-------------------------------------------------------------------------
    // 地址计数与相位
    //-------------------------------------------------------------------------
    reg  [11:0] x_cnt;      // 0 .. SW-1
    reg  [11:0] y_cnt;      // 0 .. SH-1
    reg  [23:0] even_pix;   // 偶数 x 的像素（等奇数 x 来配对）
    reg  [26:0] ps_r;       // 奇数 x 那一拍锁存的 3 通道对和
    reg         b1, b2;     // 读通流水有效标志（两级，配合 RAM 的读延迟）

    wire        x_odd = x_cnt[0];
    wire        y_odd = y_cnt[0];

    // 3 通道对和（9 bit）：偶数像素 + 奇数像素
    wire [8:0]  ps_r_c = {1'b0, even_pix[23:16]} + {1'b0, I_pix[23:16]};
    wire [8:0]  ps_g_c = {1'b0, even_pix[15:8]}  + {1'b0, I_pix[15:8]};
    wire [8:0]  ps_b_c = {1'b0, even_pix[7:0]}   + {1'b0, I_pix[7:0]};
    wire [26:0] ps_c   = {ps_r_c, ps_g_c, ps_b_c};

    // 对和 + 行缓冲 -> 四舍五入除以 4
    wire [9:0]  sum_r = {1'b0, ram_q[26:18]} + {1'b0, ps_r[26:18]} + 10'd2;
    wire [9:0]  sum_g = {1'b0, ram_q[17:9]}  + {1'b0, ps_r[17:9]}  + 10'd2;
    wire [9:0]  sum_b = {1'b0, ram_q[8:0]}   + {1'b0, ps_r[8:0]}   + 10'd2;
    wire [23:0] out_c = {sum_r[9:2], sum_g[9:2], sum_b[9:2]};

    // 一拍"该发起读"的条件：奇数 x 且奇数 y
    wire        rd_issue = I_de && x_odd && y_odd;

    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) begin
            x_cnt    <= 12'd0;
            y_cnt    <= 12'd0;
            even_pix <= 24'd0;
            ps_r     <= 27'd0;
            b1       <= 1'b0;
            b2       <= 1'b0;
            ram_we   <= 1'b0;
            ram_waddr<= 11'd0;
            ram_wdata<= 27'd0;
            O_pix    <= 24'd0;
            O_de     <= 1'b0;
        end else if (I_start) begin
            x_cnt    <= 12'd0;
            y_cnt    <= 12'd0;
            b1       <= 1'b0;
            b2       <= 1'b0;
            ram_we   <= 1'b0;
            O_de     <= 1'b0;
        end else begin
            // 默认不写 RAM（只在偶数行、奇数 x 那一拍写）
            ram_we <= 1'b0;

            if (!I_2to1) begin
                //------------------------------------------------- 直通
                // 仍然打一拍，让两条路径延迟一致（下游只关心 O_de/O_pix 同拍）
                O_pix <= I_pix;
                O_de  <= I_de;
                b1    <= 1'b0;
                b2    <= 1'b0;
            end else begin
                //------------------------------------------------- 2:1
                if (I_de) begin
                    if (!x_odd) begin
                        // 偶数 x：先存起来等配对
                        even_pix <= I_pix;
                    end else begin
                        // 奇数 x：得到一个完整的水平对和
                        if (!y_odd) begin
                            // 偶数行：写进行缓冲（输出行 y/2 的上半）
                            ram_we    <= 1'b1;
                            ram_waddr <= x_cnt[11:1];
                            ram_wdata <= ps_c;
                        end else begin
                            // 奇数行：读上半行（地址由 ram_raddr 组合给出），下一拍出结果
                            ps_r      <= ps_c;
                        end
                    end

                    // 地址推进：x 到行尾归零并进 y
                    if (x_cnt == (SW - 12'd1)) begin
                        x_cnt <= 12'd0;
                        y_cnt <= (y_cnt == (SH - 12'd1)) ? 12'd0 : (y_cnt + 12'd1);
                    end else begin
                        x_cnt <= x_cnt + 12'd1;
                    end
                end

                // 输出流水三级：rd_issue -> b1 -> b2(O_pix) -> O_de
                //   A 拍发起读（ram_raddr 同时更新）
                //   B 拍 ram_raddr 才是 A 拍的列号 -> ram_q 在 C 拍有效
                //   C 拍算 out_c，D 拍出 O_pix/O_de
                b1 <= rd_issue;
                b2 <= b1;
                O_de <= b2;
                if (b2) O_pix <= out_c;
            end
        end
    end

endmodule
