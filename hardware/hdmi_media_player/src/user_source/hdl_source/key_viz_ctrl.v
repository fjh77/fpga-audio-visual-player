`timescale 1ns / 1ps

//=============================================================================
// 文件名  : key_viz_ctrl.v
// 功能    : KEY_4 短按 —— 字随音频跳动的总开关
//
// 语义变更（c67，2026-10-27）
// --------------------------
//   原来：KEY_4 在「字幕滚动 ↔ 柱状图可视化」之间二选一，可视化要占用整条底带。
//   现在：柱状图已删除，跳动直接作用在字幕字形上，**不再需要二选一** ——
//         字幕永远显示，KEY_4 只决定"字跳不跳"。
//   于是本模块从"显示仲裁"退化成"一个记忆位"，逻辑大幅简化：
//         原来要按档位分三种规则（自动档看记忆位 / 手动档常显），
//         现在所有档位统一看记忆位。
//
// 为什么还能简化掉"手动档常显"
// ----------------------------
//   原来的手动档常显是为了"没播音时也留一条空底框，让开关状态可辨"。
//   现在跳动不占据条带、不改变底框，字幕始终在滚，"开/关"靠肉眼直接可辨
//   （跳 vs 不跳），所以不需要靠底框状态提示。MANUAL_ALWAYS 参数随之删除。
//
// 按键归属
// --------
//   gate_ok 仍然排除手动档（period_sel == 2'd3）：
//     手动档的 KEY_4 是"播 / 停当前图配套语音"（sd_card_bmp.v:697 man_audio_key_w），
//     那个功能要保留 —— 手动档正是靠它播音，播起来字才"随音频跳"。
//   排除条件同原来：
//     SW3=1  -> osd_ctrl 拿 key_period_press 做"亮度-/音量-"      -> 排除
//     SW1=1  -> 菜单打开，按键语义归菜单                          -> 排除
//     SW4=0  -> 整机锁定                                          -> 排除
//
// 时钟域
// ------
//   本模块在 sd_card_clk(100MHz) 域：key_press(=sd_key3_press)、period_sel、
//   sw1_s2 / sw3_sync / sw4_sync 全部同域。
//   输出 o_show 是**单 bit 电平**，跨到 video_clk 只需 2 级同步（顶层已做）。
//=============================================================================

module key_viz_ctrl #(
    // 上电默认：c67 改为 1（跳动常开）。
    //   理由：跳动不再是"额外图层"，就是字幕的默认行为；3s/10s 档没音频时
    //   dy 自然是 0，不会产生任何副作用，不需要为此把默认关掉。
    parameter       KEY_ON_INIT = 1'b1
)(
    input             clk,          // sd_card_clk 100MHz
    input             rst,          // 高有效同步复位（接 rst_all）

    // ---- 按键（已去抖的单拍脉冲，来自 sd_card_bmp 的 o_key3_press）----
    input             key_press,    // 顶层 sd_key3_press

    // ---- 状态输入（均已在本域）----
    input      [1:0]  period_sel,   // 0讲解 1三秒 2十秒 3手动
    input             sw1,          // 1 = 设置菜单打开
    input             sw3,          // 1 = 参数调节中（亮度/对比度/音量）
    input             sw4,          // 1 = 按键有效，0 = 整机锁定

    // ---- 输出 ----
    output reg        o_key_on,     // KEY_4 记忆（1 = 字随音频跳动）
    output            o_show        // 送给 banner_scroll 的 I_bounce
);

    //-------------------------------------------------------------------------
    // KEY_4 短按翻转记忆位（手动档排除，那里按键归 sd_card_bmp）
    //-------------------------------------------------------------------------
    wire gate_ok = sw4 & ~sw3 & ~sw1 & (period_sel != 2'd3);

    always @(posedge clk or posedge rst) begin
        if (rst)
            o_key_on <= KEY_ON_INIT;
        else if (key_press & gate_ok)
            o_key_on <= ~o_key_on;
    end

    //-------------------------------------------------------------------------
    // 输出：所有档位统一看记忆位（不再分档位）
    //-------------------------------------------------------------------------
    assign o_show = sw4 & o_key_on;

endmodule
