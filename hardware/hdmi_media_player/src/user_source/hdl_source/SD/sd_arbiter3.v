//=============================================================================
// 文件名  : sd_arbiter3.v
// 功能    : SD/TF 卡扇区读三方仲裁器（阶段 3a 新增）
//
// 为什么需要它
// ------------
//   sd_card_top 的 sd_sec_read/sd_sec_read_addr 口子只有一套：
//   谁拉高就按谁的地址读 512 字节。原来工程里有两个请求者：
//       * bmp_read    （显示通路：上电扫图 + 每张图装载）
//       * wav_player  （语音通路：后台预取扇区）
//   这两个已经在 sd_card_bmp.v 里用一段内联 always 做了二选一仲裁。
//   阶段 3a 要把 fat32_dir 这个第三个请求者接进来，所以：
//       * 把原来那段内联仲裁逻辑原样搬进本模块（行为逐拍等价）；
//       * 再加一路 FAT 请求，并且给它最低优先级。
//
// 优先级与"现有通路绝对不能被打断"的保证
// --------------------------------------
//   优先级：bmp_read（最高） > wav_player > fat32_dir（最低）
//   并且是"许可式锁存"而不是事后纠正：
//       * 只有在 xfer_active==0（空闲）时才接受新请求；
//       * 一旦接了某个请求者，就把 owner 锁死，地址也锁死，
//         直到对方的 sd_sec_read_end 到达才释放。
//     -> 正在传输的那一次不可能被换地址（换地址=读到半个扇区）；
//     -> 现有通路的请求电平一直保持到 sd_sec_read_end 才落下
//        （bmp_read / wav_player 都是这么写的），所以"我这一拍没被批准、
//         下一拍就丢了"的情况不存在；
//     -> FAT 解析只在两个现有通路都不请求时才拿到卡，
//        而且 FAT 只读 MBR/DBR/根目录共几个扇区，占用可忽略。
//
//   为什么不用"按拍轮转"？轮转会让现有通路的请求多等几拍才被受理，
//   显示/音频对延迟敏感，这正是要避免的。所以这里用固定优先级。
//
// 时钟域
// ------
//   全部信号都在同一个时钟域（sd_card_bmp 里的 clk = sd_card_clk = 100MHz）。
//   没有任何跨时钟域信号，所以本模块内不需要两级同步器。
//   跨域发生在别处：wav_player 的音频输出到 clk_audio 由它自己在内部处理。
//
// 2026-10 新增：o_grant_bmp / o_grant_wav / o_grant_fat（授权指示）
// ----------------------------------------------------------------------
//   背景（真硬件上抓到的 bug）：
//     阶段 3b 上板后 HDMI 全黑，数码管读出 fat_err=12（ERR_SECTOR_TO 扇区超时），
//     文件表一张图都没挑出来。根因是请求者的"等扇区数据超时"计数器
//     从发出请求就开始计时，而低优先级请求者这段时间可能全在排队：
//     bmp 是最高优先级，它一读就是一整张图（1801 扇区 × 每扇区 ≈ 一百多微秒
//     ≈ 0.85 秒），FAT 的请求在队列里等，超时却已经跑完了。
//     —— "排队时间被错算成传输超时"是设计缺陷，不是参数没调好。
//
//   修法（分两层）：
//     第 1 层（治本，本模块配合）：仲裁器把"你被授权了"告诉每一路
//         （o_grant_*），请求者的超时计数器只在被授权期间累加，
//         排队期间不累加。
//     第 2 层（保底）：请求者那侧的阈值从 16384 拍（= 164µs @100MHz，
//         恰好等于 25MHz SPI 传一个扇区的纯数据时间）放宽到 20ms 量级，
//         见 fat32_dir.v / fat32_file.v 的 TO_LIMIT 注释。
//
// 为什么用"授权指示"而不是"让仲裁器顺便管超时"
//     超时是请求者自己的状态机才知道的事（它知道自己是不是在等第一个字节、
//     还是收了一半断流了）；仲裁器只该回答"现在轮到谁"。职责分开，
//     而且新增的三根输出是纯组合，不动任何仲裁逻辑 —— 现有 bmp/wav 通路
//     逐拍不变（这是本项目的硬约束：旧通路一行都不能删、不能改行为）。
//
// 位宽约定
// --------
//   所有字面量写明确位宽；不做任何隐式截断。
//=============================================================================

`timescale 1ns / 1ps

module sd_arbiter3 (
    input             clk,
    input             rst,              // 异步复位，高有效（与本工程其余模块一致）

    // ---------------- 请求者 1：bmp_read（显示，最高优先级）----------------
    input             bmp_req,          // 电平：一直保持到 bmp_end 回来
    input      [31:0] bmp_lba,
    output            bmp_dat_vld,
    output     [7:0]  bmp_dat,
    output            bmp_end,

    // ---------------- 请求者 2：wav_player（语音，中优先级）----------------
    input             wav_req,
    input      [31:0] wav_lba,
    output            wav_dat_vld,
    output     [7:0]  wav_dat,
    output            wav_end,

    // ---------------- 请求者 3：fat32_dir（FAT 解析，最低优先级）----------
    input             fat_req,
    input      [31:0] fat_lba,
    output            fat_dat_vld,
    output     [7:0]  fat_dat,
    output            fat_end,

    // ---------------- 到 sd_card_top（卡侧只有一套口子）-------------------
    output            sd_req,
    output     [31:0] sd_lba,
    input      [7:0]  sd_dat,
    input             sd_dat_vld,
    input             sd_end,

    // ---------------- 现场调试（给数码管/LED 看谁在占卡）------------------
    output            o_busy,           // 1 = 有一次扇区传输正在进行
    output     [1:0]  o_owner,          // 0=空闲 1=bmp 2=wav 3=fat

    // ---------------- 2026-10 超时修复新增：三路"授权"指示 -------------
    //
    // 语义：o_grant_X = 1 表示"X 这一路的本次请求已经被仲裁器
    //                  批准，卡现在归它"，高电平区间 = 从仲裁器接下这次请求的
    //                  那一拍起，到 sd_end 那一拍止。
    //
    // 为什么必须引出来（本模块存在的那个真 bug）：
    //   请求者（fat32_dir / fat32_file）内部有一个"等扇区数据"的超时计数器，
    //   它以前是从发出请求就开始计时的。可是低优先级请求者发出请求之后，
    //   可能绝大部分时间都在这里排队（bmp 一次占卡就是一整张图 ≈ 0.85 秒），
    //   根本没轮到它 —— 排队时间被错算成了"传输超时"，于是必然误报。
    //   有了这根线，请求者就能把"排队期"从超时计时里排除掉：
    //       i_granted=0  -> 我在排队，不计时
    //       i_granted=1  -> 卡已经在给我传了，这时断流才算真超时
    //
    // 对现有通路(bmp/wav)行为的影响：零
    //   这三根线是纯组合（xfer_active & owner 的两个派生位），
    //   没有新增任何寄存器、没有改动下面任何一句仲裁逻辑，
    //   所以 bmp/wav 的受理时序与改动前逐拍等价。
    //   （bmp_read / wav_player 内部本来就没有扇区超时计数器，它们不用这根线；
    //     接出来主要是给 FAT 两路用的，bmp 那一路给 bmp_load_fat 用。）
    output            o_grant_bmp,
    output            o_grant_wav,
    output            o_grant_fat
);

    //-------------------------------------------------------------------------
    // 传输状态
    //   xfer_active : 0 = 空闲可接新请求，1 = 已锁定某一路
    //   owner       : 2'd1=bmp / 2'd2=wav / 2'd3=fat
    //-------------------------------------------------------------------------
    reg        xfer_active;
    reg [1:0]  owner;

    // 组合：owner 的两个派生位。写成 wire 而不是在 always 里再赋一次，
    // 免得同一个信号出现两个驱动（verilog_lint 会报，综合器也不认）。
    wire       own_bmp = (owner == 2'd1);
    wire       own_wav = (owner == 2'd2);
    wire       own_fat = (owner == 2'd3);

    //-------------------------------------------------------------------------
    // 仲裁：固定优先级 + 锁存（见文件头说明）
    // 优先级顺序就是下面 if-else 的顺序，改顺序即改优先级
    // 只有在 !xfer_active 时才看请求，决不会中途换 owner
    //-------------------------------------------------------------------------
    always @(posedge clk or posedge rst) begin
        if (rst) begin
            xfer_active <= 1'b0;
            owner       <= 2'd0;
        end else if (!xfer_active) begin
            if (bmp_req) begin
                xfer_active <= 1'b1;
                owner       <= 2'd1;
            end else if (wav_req) begin
                xfer_active <= 1'b1;
                owner       <= 2'd2;
            end else if (fat_req) begin
                xfer_active <= 1'b1;
                owner       <= 2'd3;
            end
        end else if (sd_end) begin
            // 一次传输结束（卡侧 sd_sec_read_end 是单拍脉冲）
            xfer_active <= 1'b0;
            owner       <= 2'd0;
        end
    end

    //-------------------------------------------------------------------------
    // 去卡侧：地址按 owner 组合选择（必须与 sd_req 同拍，不能多打一拍）
    //-------------------------------------------------------------------------
    assign sd_req = xfer_active;
    assign sd_lba = own_wav ? wav_lba :
                    own_fat ? fat_lba :
                              bmp_lba;      // 默认给 bmp（owner 为 0 时取不到值也无所谓）

    //-------------------------------------------------------------------------
    // 回程信号按 owner 分流
    //   数据本身是广播的（同一拍只有一路在收，广播不会串），
    //   但 end / data_valid 必须门控：否则另一方会收到不属于自己的
    //   脉冲，字节计数错乱（原来内联仲裁里就踩过这个问题）。
    //-------------------------------------------------------------------------
    assign bmp_dat     = sd_dat;
    assign wav_dat     = sd_dat;
    assign fat_dat     = sd_dat;

    assign bmp_dat_vld = sd_dat_vld & own_bmp;
    assign wav_dat_vld = sd_dat_vld & own_wav;
    assign fat_dat_vld = sd_dat_vld & own_fat;

    assign bmp_end     = sd_end & own_bmp;
    assign wav_end     = sd_end & own_wav;
    assign fat_end     = sd_end & own_fat;

    //-------------------------------------------------------------------------
    // 调试输出
    //-------------------------------------------------------------------------
    assign o_busy  = xfer_active;
    assign o_owner = owner;

    //-------------------------------------------------------------------------
    // 2026-10 超时修复新增：授权指示（纯组合，见端口注释）
    //   own_* 就是上面那三个"owner 的派生位"，所以这里一个门都不多：
    //   o_grant_x 与 sd_dat_vld/fat_end 那两个回程门控用的是同一个条件，
    //   语义天然一致（"卡归我"这件事只有一处定义）。
    //-------------------------------------------------------------------------
    assign o_grant_bmp = xfer_active & own_bmp;
    assign o_grant_wav = xfer_active & own_wav;
    assign o_grant_fat = xfer_active & own_fat;

endmodule
