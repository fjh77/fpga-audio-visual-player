//=============================================================================
// 文件名  : audio_volume.v
// 功能    : 音频左右声道的音量缩放（增益）
//
// 数学
// ----
//   out = clamp( (in * gain_q7) >> 7 , -2^23 , 2^23-1 )
//
//   in       : 有符号 24bit 二补码 PCM
//   gain_q7  : Q7 无符号，128 = 1.0x
//
// 为什么增益是 unsigned 而样本是二补码
// ------------------------------------
//   两个 W 位二补码数相乘，只要各自先扩展到乘积宽度，
//   再用无符号乘法取低 W 位，结果就是正确的二补码积（模 2^W 一致）。
//   增益恒非负，所以零扩展即可。这样全程不需要 signed 关键字
//   （本工程工具链对 signed 声明兼容性不佳）。
//
// 全组合、无寄存
// --------------
// 不能加寄存器：audio_valid 脉冲与样本数据必须同拍到达 HDMI 核，
//   一旦给数据加了流水延迟而没同步延迟 valid，样本就会被错位采走。
//   乘法本身很窄（24bit x 8bit，单个 18x18 DSP 就够），25MHz 下时序富裕。
//
// 饱和
// ----
//   增益最高约 1.42x，若样本本身接近满量程就会溢出，
//   所以必须做 24bit 有符号饱和，否则会从最大正数翻转到最大负数（爆音）。
//=============================================================================

module audio_volume (
    input      [23:0]   I_left,
    input      [23:0]   I_right,
    input      [7:0]    I_gain_q7,      // 0..182（70 -> 约 1.0x）
    output     [23:0]   O_left,
    output     [23:0]   O_right
);

    function [23:0] vol_ch;
        input [23:0] sin;
        input [7:0]  g;
        reg   [31:0] s32, g32, prod32, q;
        begin
            s32    = { {8{sin[23]}}, sin };      // 符号扩展到 32 位
            g32    = { 24'd0, g };               // 零扩展（增益非负）
            prod32 = s32 * g32;                  // 取低 32 位即正确二补码积
            q      = { {7{prod32[31]}}, prod32[31:7] };   // 算术右移 7（手工复制符号位）

            // 24bit 有符号饱和：上限 0x7FFFFF，下限 0x800000
            // 注意 q[31]=1（负）时用无符号比较仍然正确：
            //   两个负数比大小，无符号序与二补码序一致
            if (q[31]) vol_ch = (q < 32'hFF800000) ? 24'h800000 : q[23:0];
            else       vol_ch = (q > 32'h007FFFFF) ? 24'h7FFFFF : q[23:0];
        end
    endfunction

    assign O_left  = vol_ch(I_left,  I_gain_q7);
    assign O_right = vol_ch(I_right, I_gain_q7);

endmodule
