//=============================================================================
// 文件名  : osd_ctrl.v
// 功能    : OSD 参数控制 —— 亮度 / 对比度 /（后续）音量的寄存器与菜单裁决
//
// 参数表示
// --------
//   对外（寄存器）：0 ~ 100，步长 10（PARAM_STEP）
//       亮度   默认 50（中性）
//       对比度 默认 50（中性，gain = 1.0）
//       音量   默认 80（0.80x）
//
//   对视频域（换算后）：
//       O_gain_q7 : Q7 组合增益 = 对比度 kc × 亮度 kb / 128（128 = 1.0x）
//                   实测范围约 0.61x（对比度 0，保黑）~ 1.30x（对比度 100）
//       O_offset  : 8bit 二补码亮度偏移，范围 -64 ~ +64
//
//   换算用定点乘加，不用除法也不用查表：
//       0..100 -> 0..128 倍率 1.28，用 *41 >>5 逼近（41/32 = 1.28125）
// c=50 -> 64+64 = 128 (1.0x)
// c=100 -> 64+128 = 192 (1.5x)
// b=50 -> off_u=64 -> offset=0
//
// 时钟域
// ------
//   100MHz（sd_card_clk）。因为消抖后的按键脉冲来自 sd_card_bmp，就在那个域里，
//   避免再把脉冲跨到 25MHz（跨域脉冲宽度只有 10ns，25MHz 域会漏掉）。
//   参数是慢变量，再跨到视频域时用 toggle 握手搬过去。
//
// 功能
// ----
//   SW3 = 1 进入调节模式，此时三键含义与平时不同：
//       KEY_2  切换参数（亮度 -> 对比度 -> 音量，三页轮转）
//       KEY_3  当前参数 +PARAM_STEP
//       KEY_4  当前参数 -PARAM_STEP
//   SW3 = 0 时参数保持不变（退出调节不清值，param_sel 也保持）。
//
//   三个参数各自换算成 Q7 增益（128 = 1.0x），
//   由 O_param_tgl 翻转通知下游模块一次性锁存全部值
//   （多比特值不能逐位同步，变化瞬间会撕裂）。
//
//   ★ 对比度已于 2026-10-30 接入调节流程（此前注释写"未接入"，已过时）：
//     O_contrast 经下方"对比度锥度"查表转成 kc，再与亮度 kb 合成 O_gain_q7 / O_venh_off
//     送 video_enhance。上行绕中灰旋转（压暗部提亮部），下行纯增益保黑（详见该段注释）。
//=============================================================================

module osd_ctrl (
    input               I_clk,          // 100MHz
    input               I_rst,

    // ---- 拨码（已在顶层做过 2 级同步）----
    input               I_sw3,          // 1 = 进入 OSD 参数调节

    // ---- 消抖后的按键单拍脉冲（来自 sd_card_bmp）----
    input               I_key1_press,   // 板载 KEY_2(B2)
    input               I_key2_press,   // 板载 KEY_3(B1)
    input               I_key3_press,   // 板载 KEY_4(C1)

    // ---- 参数寄存器（0~100）----
    output reg [6:0]    O_brightness,
    output reg [6:0]    O_contrast,
    output reg [6:0]    O_volume,       // 默认 70（对应约单位增益）

    // ---- 换算后的系数（已寄存，便于跨域采样稳定）----
    output reg  [7:0]   O_brt_gain,     // 组合增益 Q7 = 对比度C x 亮度B >>7（63~215）
    output reg  [7:0]   O_venh_off,     // 偏移（偏置 128）；降对比度时恒为 128=保黑
    output reg  [7:0]   O_knee,         // 高光肩起点（输出域 0~255）
    output reg  [7:0]   O_vol_q7,       // 音量增益 Q7，128 = 1.0x
    // 当前选中的参数（0=亮度 1=对比度 2=音量），供 OSD 显示
    output reg  [1:0]   O_param_sel,
    // 参数更新翻转信号：目标域的模块检测它的变化，一次性锁存上面所有值
    //（多比特值不能用简单的 2 级同步逐位跨域，变化瞬间会撕裂）
    output reg          O_param_tgl,

    // ---- 给 sd_card_bmp：屏蔽翻页 ----
    output              O_block_page
);

    //-------------------------------------------------------------------------
    // 参数换算 + 跨域握手（组合算、寄存出）
    //-------------------------------------------------------------------------
    // 亮度改为乘法式，不再是叠加式
    //
    //   叠加式 out = in + offset 的问题：
    //       对三通道加同一个常数，暗通道会先被截断到 0，色相被破坏。
    //       例：原像素 (200,50,30) 橙色，offset -96 后变成 (104,0,0) 纯红。
    //       视觉上就是"色彩度不符、失真"。
    //
    //   乘法式 out = in * B/128 对三通道同比例缩放：
    //       色相完全保持，饱和度完全保持，暗部按比例变暗而不是糊成黑块。
    //
    //   关键：不需要改 video_enhance.v 的公式，只要把参数喂成下面这样，
    //   它算出来的结果就恒等于纯缩放：
    //       I_gain_q7 = G = C*B/128      （C 是对比度，当前固定 128）
    //       I_offset  = B - 128
    //   代入 (in-128)*G/128 + 128 + offset：
    // = (in-128)*B/128 + B = B*in/128 ← 纯缩放
    //   以后恢复对比度时只要把 G 换成 C*B/128 即可，公式不用动。
    //
    //   亮度增益 B 的映射（非对称，向上留余量）：
    //       b=0   -> B=39  (0.30x)
    //       b=50  -> B=128 (1.00x 中性)
    //       b=100 -> B=192 (1.50x)
    //-------------------------------------------------------------------------
    // 亮度增益范围大幅加宽，否则乘法式每档变化太小、感觉"调不动"：
    //       b=0   -> B=19  (0.15x)  很暗
    //       b=50  -> B=128 (1.00x 中性)
    //       b=100 -> B=237 (1.85x)  很亮
    //   斜率 109/50 = 2.18，用 140/64 = 2.1875 逼近
    //   配合 PARAM_STEP=10 时，每按一次约变 21 级（像素128处），清晰可见。
    // 位宽陷阱
    //   7 位字面量最大只能写 127。写成 7'd140 时 Verilog 会静默截断
    //   成 140 & 0x7F = 12 —— 编译不报错、仿真不报错，
    //   只是斜率变成 12/64 而不是 140/64，亮度每档只动 1 级，
    //   肉眼完全看不出（表现为"怎么调都没反应"）。
    //   所以这里必须用 8'd140。
    //-------------------------------------------------------------------------
    // 位宽陷阱之二：上下文决定宽度（比 7'd140 那个更隐蔽）
    //
    //   错误写法：
    //       wire [7:0] y = (a * b) >> 6;
    //   Verilog 的 * + - 是上下文决定宽度的：赋值目标只有 8 位，
    //   于是 a*b 的乘积先被截成 8 位，然后再右移 —— 结果全错。
    //   编译不报错、仿真不报错，只是数值离谱。
    //
    //   实测后果（这就是"亮度只有 125~131、音量只有 0/3/6、
    //   音量 0/50/100 都静音"的真正原因）：
    //       音量 80 档 -> 乘积 3280 截成 8 位 = 208 -> >>5 = 6 -> 只有 0.047x！
    //       音量 50 档 -> 乘积 2050 截成 8 位 =   2 -> >>5 = 0 -> 静音！
    //
    //   正确写法：先用显式足够宽的中间信号接住乘积，
    //   右移也在同样宽的上下文里做，最后再取低 8 位。
    //   这样每一步的位宽都由我们自己指定，不受赋值目标影响。
    //-------------------------------------------------------------------------
    //-------------------------------------------------------------------------
    // 亮度 -> 乘法增益（Q7，128 = 1.0x）
    //
    // 为什么最终选乘法
    //   数学上只有纯乘法能精确保持色相和饱和度：
    //       加偏移  out=in+k            -> 暗通道被截断，饱和度变
    //       曲线    out=in+a*in*(255-in) -> 逐通道提中间调，饱和度变
    //       乘法    out=in*k            -> 色相和饱和度精确不变
    //   "泛白/泛黑"的真正根因就是逐通道非线性操作改变了饱和度，
    //   不是削顶。所以这里回到乘法，用高光软膝解决削顶。
    //
    //   斜率 38/50 = 0.76，用 49/64 = 0.7656 逼近：
    //       b=0   -> 增益  90  (0.703x)
    //       b=50  -> 增益 128  (1.000x 原样)
    //       b=100 -> 增益 166  (1.297x)
    //
    // 范围为什么只给 ±30%
    //   这是物理取舍，不是没调好：
    //       - 提亮超过 1.3x 时，素来较亮的像素会撞上 255 而丢失层次
    //         （软膝能平滑掉一部分，但信息已经没了）-> "泛白"
    //       - 压暗低于 0.7x 时，暗部会大面积落到 1 个 LSB 以下
    //         -> "泛黑"
    //   商业显示器的亮度旋钮大致也就是 ±20~30% 的行程，
    //   正因为再大就一定会在两端露出破绽。
    //   真要让很暗/很亮的素材也能看清，正确做法是调对比度或
    //   做 Gamma，而不是继续加大亮度行程。
    //   必须用宽中间信号接乘积，避免上下文宽度截断。
    //-------------------------------------------------------------------------
    wire [14:0] b_dn_p = (7'd50 - O_brightness) * 8'd49;
    wire [14:0] b_up_p = (O_brightness - 7'd50) * 8'd49;
    wire [14:0] b_dn_x = b_dn_p >> 6;
    wire [14:0] b_up_x = b_up_p >> 6;
    wire [7:0]  b_dn   = b_dn_x[7:0];                     // b=0..50  -> 0..38
    wire [7:0]  b_up   = b_up_x[7:0];                     // b=50..100 -> 0..38
    wire [7:0]  brt_w  = (O_brightness >= 7'd50) ? (8'd128 + b_up)
                                                 : (8'd128 - b_dn);

    //-------------------------------------------------------------------------
    // 对比度锥度（2026-10-30 新增，同日三次修正：下行改查表）
    //
    //   上行（增加对比度）：  50 -> 128（1.00x），100 -> 166（1.30x）  系数 49/64
    //   下行（降低对比度）：  改查表，每档感知递增（见下）
    //
    //   ★ 下行为什么从线性改查表：
    //     保黑模型下"降对比度 = 整幅等比压暗"，线性锥度每档只差 5~7%
    //     （0.78x/50 档行程 → 每档 6.2% 增益差），上板感受是"拧了没反应"。
    //     查表把行程重新分配：靠近 50 的档位步幅小（免得轻轻一按就突变），
    //     靠近 0 的档位步幅大（要一眼能看出变柔），实测 04.bmp 的中位亮度
    //     相对变化为：
    //         C=40 -5.5% | 30 -11.7% | 20 -21% | 10 -30% | 0 -39%
    //     （线性表只有 -4/-9/-13/-18/-23%。）
    //   C=0 时白点 255->155：够暗但不过火；要更亮可以把亮度旋钮往上加
    //   （保黑段是乘性增益，亮度仍然有效）。
    //
    //   ★ 下行为什么收窄到 0.61x（kc=78）：下行是纯增益（见"保黑"一节），
    //     增益就是整幅画面等比压暗。0.61x 是"明显但不至于关灯"的边界，
    //     再往下白点掉进 130 以下，展品图会像打了夜灯。
    //     上行不动是因为它走的是另一条路（绕中灰），没有这个问题。
    //-------------------------------------------------------------------------
    wire [6:0] c_step = 7'd50 - O_contrast;   // 0..50；PARAM_STEP=10 只会出整十
    reg  [7:0] c_dn_w;
    always @(*) begin
        case (c_step)
        7'd0:  c_dn_w = 8'd0;                 // C=50  kc=128（中性直通）
        7'd10: c_dn_w = 8'd7;                 // C=40  kc=121
        7'd20: c_dn_w = 8'd16;                // C=30  kc=112
        7'd30: c_dn_w = 8'd27;                // C=20  kc=101
        7'd40: c_dn_w = 8'd38;                // C=10  kc=90
        7'd50: c_dn_w = 8'd50;                // C=0   kc=78（0.609x）
        // 非整十档兜底：按线性比例（PARAM_STEP 若改小也不会算错）
        default: c_dn_w = {1'b0, c_step[5:0]} + (c_step >> 1);
        endcase
    end
    wire [14:0] c_up_p = (O_contrast - 7'd50) * 8'd49;
    wire [7:0]  c_up   = (c_up_p >> 6) & 8'hFF;
    wire [7:0]  ctr_w  = (O_contrast >= 7'd50) ? (8'd128 + c_up)
                                               : (8'd128 - c_dn_w);

    //-------------------------------------------------------------------------
    // 两旋钮合成（2026-10-30 修正，同日二次修正：下行改保黑）
    //
    //   增益：G = kc*kb（Q7 x Q7 >> 7，仍是 Q7）—— 两段都用
    //   偏移：kc >= 128（增强）时 O = kb - G，绕 128 旋转
    //         kc <  128（减弱）时 O = 0，纯增益保黑
    //
    //   ★ 保黑那一段的理由见下面 off_r_w 处的长注释：正偏移会把黑位
    //     和饱和度一起毁掉（实测饱和度 -42%），这是上板泛白的根因。
    //
    //   实测范围：
    //     G   70 ~ 215（0.55x ~ 1.68x）
    //     O   -49 ~ 0    （kc<128 恒 0；kc=166,kb=166 时最负 -49）
    //     off_w = O+128 ∈ [79,128]，无符号 8 位装得下。
    //-------------------------------------------------------------------------
    //-------------------------------------------------------------------------
    // 输出级：两级流水（2026-10-30）
    //   组合直连时实测最差路径 = 11 级逻辑 / 18.7ns，终点 O_knee_reg，
    //   在 62.5MHz（16ns）下差 -3ns。罪魁是三级乘法串联：
    //       锥度 ×49  ->  8×8 合成  ->  膝点 ×10
    //   这三组值都是**准静态**的（只在用户拧旋钮时变），加流水没有副作用。
    //   ★ 翻转位必须与数据同步延迟：否则视频域会在数据更新前一拍锁存到旧值。
    //-------------------------------------------------------------------------
    reg  [7:0] ctr_r, brt_r, vol_r;    // 第一级：锥度结果
    reg  [7:0] comb_r;                 // 第二级：合成增益
    reg  [1:0] chg_sr;                 // 变化沿延迟 2 拍，与数据对齐

    wire [15:0] comb_p_r = ctr_r * brt_r;

    // 偏移（第三级组合，输入已是寄存器）
    //
    // ★★ 降低对比度时必须保黑：kc < 128 段偏移强制 0（2026-10-30 二次修正）
    //
    //   旧写法 O = kb - G 在 kc<128 时恒为正（= kb*(1-kc/128)），含义是
    //   "绕 128 旋转"：out = (in-128)*kc/128 + 128。这在数值上没错，
    //   但上板后对比度调到 30 以下整幅画面泛白，原因是两条：
    //
    //   1) 本工程四张展品图的中位亮度**都是 44**（不是 128），p5 = 0。
    //      收缩到 0.70x 时偏移 = 38，于是黑(0)->38、中位(44)->69，
    //      全屏被整体抬高 20~30 个码值 —— 在暗环境里就是"黑底变灰"。
    //
    //   2) 更致命的是饱和度：三通道加同一个偏移，等于把色差往一起挤。
    //      实测 01.bmp：饱和度 0.732 -> 0.422（-42%），红棕底直接变粉白。
    //      （这与本工程亮度通路"只有纯乘法能保持色相/饱和度"是同一条原理，
    //        原注释里写了，但对比度这一路当初没照着做。）
    //
    //   改成纯增益 out = in*G/128 后，三通道同比例缩放：
    //      饱和度 0.732 -> 0.735（不变），黑 0 -> 0，代价只是整幅暗 22%。
    //
    //   这也正是**显示器 Contrast 旋钮的真实行为**：调的是白点增益，
    //   黑点不动。图像软件那种"绕中灰"是另一套模型（会牺牲黑位和饱和度）。
    //
    //   增加对比度（kc>=128）仍保持绕中灰：它不需要偏移为正，不会泛白，
    //   而且"压暗部 + 提亮部"正是对比度增强想要的效果。
    //   两段在 kc=128 处偏移都是 0，切换无跳变。
    wire [8:0]  off_r_w  = (ctr_r >= 8'd128)
                         ? ({1'b0, brt_r} + 9'd128 - {1'b0, comb_r})
                         : 9'd128;

    // 高光肩起点：增益 <= 1.0x 给 255（直通），>1.0x 按 0.3125 递减
    //   0.3125 = 1/4 + 1/16，用两次移位相加实现，省掉一个乘法器：
    //       d=38 (G=166) -> 9+2 = 11 -> knee=244（白仍是 255）
    //   系数来源：要求 1.3x 时 in=255 仍输出 255，需 K>=243。
    wire [7:0]  kd       = comb_r - 8'd128;   // 0~87（comb_r 最大 215）
    wire [7:0]  knee_r_w = (comb_r <= 8'd128) ? 8'd255
                          : (8'd255 - (kd >> 2) - (kd >> 4));

    //-------------------------------------------------------------------------
    // 音量 -> Q7 增益，采用对数(dB)锥度—— 这才是市面上的标准做法
    //
    //   线性幅度的问题：50% 处才 -6dB，听起来仍然很响；而低档位掉得飞快。
    //   结果就是听感上"只有几档"，高低两端都白给。
    //   dB 锥度让每一档的响度变化一样多，这才是音量旋钮该有的手感。
    //
    //   本设计：每档 3dB，共 11 档（0dB ~ -30dB）
    //       音量 100 ->    0dB -> 128 (1.000x)
    //       音量  90 ->   -3dB ->  91
    //       音量  80 ->   -6dB ->  64 (0.500x)
    //       音量  70 ->   -9dB ->  45
    //       音量  50 ->  -15dB ->  23 (0.180x)
    //       音量   0 ->   静音 ->   0
    //
    //   用查表而不是算指数：先求 volume/10（0~10），再查 11 项目表。
    //   这样不依赖 PARAM_STEP，也不需要除法或乘法。
    //-------------------------------------------------------------------------
    //-------------------------------------------------------------------------
    // P&R 修复（2026-10-11，详见 _snapshots\_pnr_run\PNR_FIX.md）
    //
    //   原写法（已被替换）：
    //       for (vi = 0; vi < 10; vi = vi + 1)
    //           if (v_rem >= 7'd10) begin v_idx = v_idx + 1; v_rem = v_rem - 10; end
    //   语义上等于 min(floor(volume/10), 10)，但综合出来是10 级串联的
    //   「比较器 + 减法器」组合长链。TD 实测：
    //        Logic Level = 26 ( ADDER=16 LUT3=6 LUT5=2 LUT4=2 )
    //        sd_card_clk (100MHz / 10ns) 上 Slack = -16.785ns
    //   —— 这是全工程唯一低于 -7ns 的路径，也是 WNS 的全部来源。
    //   放置器为了它做大量徒劳的时序优化，间接加剧了布线拥塞。
    //
    //   新写法：把 volume -> volume/10 做成一级并行译码（11 组 case）。
    //   对 0~127 的任意 volume，结果与原循环逐值完全一致：
    //        0..9 -> 0    40..49 -> 4    80..89 -> 8
    //       10..19 -> 1   50..59 -> 5    90..99 -> 9
    //       20..29 -> 2   60..69 -> 6    >=100  -> 10
    //       30..39 -> 3   70..79 -> 7
    //   （原循环也只有 10 次迭代，所以天然在 10 处封顶，default 必须给 10）
    //   等价性由 tools\osd_sim\run_osd_sim.py 逐值对照证明（含负对照）。
    //-------------------------------------------------------------------------
    reg [3:0] v_idx;            // volume/10（0~10）

    always @(*) begin
        case (O_volume)
            7'd0,  7'd1,  7'd2,  7'd3,  7'd4,  7'd5,  7'd6,  7'd7,  7'd8,  7'd9:  v_idx = 4'd0;
            7'd10, 7'd11, 7'd12, 7'd13, 7'd14, 7'd15, 7'd16, 7'd17, 7'd18, 7'd19: v_idx = 4'd1;
            7'd20, 7'd21, 7'd22, 7'd23, 7'd24, 7'd25, 7'd26, 7'd27, 7'd28, 7'd29: v_idx = 4'd2;
            7'd30, 7'd31, 7'd32, 7'd33, 7'd34, 7'd35, 7'd36, 7'd37, 7'd38, 7'd39: v_idx = 4'd3;
            7'd40, 7'd41, 7'd42, 7'd43, 7'd44, 7'd45, 7'd46, 7'd47, 7'd48, 7'd49: v_idx = 4'd4;
            7'd50, 7'd51, 7'd52, 7'd53, 7'd54, 7'd55, 7'd56, 7'd57, 7'd58, 7'd59: v_idx = 4'd5;
            7'd60, 7'd61, 7'd62, 7'd63, 7'd64, 7'd65, 7'd66, 7'd67, 7'd68, 7'd69: v_idx = 4'd6;
            7'd70, 7'd71, 7'd72, 7'd73, 7'd74, 7'd75, 7'd76, 7'd77, 7'd78, 7'd79: v_idx = 4'd7;
            7'd80, 7'd81, 7'd82, 7'd83, 7'd84, 7'd85, 7'd86, 7'd87, 7'd88, 7'd89: v_idx = 4'd8;
            7'd90, 7'd91, 7'd92, 7'd93, 7'd94, 7'd95, 7'd96, 7'd97, 7'd98, 7'd99: v_idx = 4'd9;
            default:                                                                v_idx = 4'd10;
        endcase
    end

    reg [7:0] vol_w;
    always @(*) begin
        case (v_idx)
            4'd0:    vol_w = 8'd0;      // 音量   0   静音
            4'd1:    vol_w = 8'd6;      // 音量  10  -27dB
            4'd2:    vol_w = 8'd8;      // 音量  20  -24dB
            4'd3:    vol_w = 8'd11;     // 音量  30  -21dB
            4'd4:    vol_w = 8'd16;     // 音量  40  -18dB
            4'd5:    vol_w = 8'd23;     // 音量  50  -15dB
            4'd6:    vol_w = 8'd32;     // 音量  60  -12dB
            4'd7:    vol_w = 8'd45;     // 音量  70   -9dB
            4'd8:    vol_w = 8'd64;     // 音量  80   -6dB
            4'd9:    vol_w = 8'd91;     // 音量  90   -3dB
            default: vol_w = 8'd128;    // 音量 100    0dB（= 素材原始响度）
        endcase
    end

    reg [6:0] b_d, c_d, v_d;
    reg  [1:0] sel_d;

    // 当前选中的参数：0 = 亮度，1 = 音量
    // 用 KEY_2 按键切换（不用拨码）：
    //   拨码没有反馈，容易拨在错误档位却以为"按键失灵"；按键切换更直观。
    //   SW2 现在用于转场模式（1 = 卷曲 / 0 = 推移），参数切换只能放在按键上。
    //   KEY_2 平时是翻页键，进入 OSD（SW3=1）后翻页已被屏蔽，正好复用。
    reg [1:0] param_sel;

    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) begin
            ctr_r <= 8'd128; brt_r <= 8'd128; vol_r <= 8'd128;
            comb_r <= 8'd128; chg_sr <= 2'd0;
            O_brt_gain  <= 8'd128;      // 组合增益中性（1.0x，原样输出）
            O_venh_off  <= 8'd128;      // 偏移中性（真值 0）
            O_knee      <= 8'd255;      // 中性：不压高光
            O_vol_q7    <= 8'd128;      // 音量默认 100 档 = 0dB
            O_param_sel <= 2'd0;        // 默认亮度
            O_param_tgl <= 1'b0;
            b_d         <= 7'd50;
            c_d         <= 7'd50;
            v_d         <= 7'd100;
            sel_d       <= 1'b0;
        end else begin
            // 第一级：锥度
            ctr_r <= ctr_w;
            brt_r <= brt_w;
            vol_r <= vol_w;
            // 第二级：合成增益 G = kc*kb/128
            comb_r <= comb_p_r[14:7];
            // 第三级：输出寄存器（与翻转位同拍）
            O_brt_gain  <= comb_r;
            O_venh_off  <= off_r_w[7:0];
            O_knee      <= knee_r_w;
            O_vol_q7    <= vol_r;
            O_param_sel <= param_sel;

            b_d   <= O_brightness;
            c_d   <= O_contrast;
            v_d   <= O_volume;
            sel_d <= param_sel;
            // 任一参数变化就翻转一次，供目标域一次性锁存全部值
            //   必须把 param_sel 也算进条件（切页时数值没变也要通知）。
            //   ★ chg_sr 延迟 2 拍，与上面三组输出寄存器的更新同拍 ——
            //     视频域收到翻转时，数据已经是新值。
            chg_sr <= {chg_sr[0],
                       (b_d != O_brightness) || (c_d != O_contrast) ||
                       (v_d != O_volume)     || (sel_d != param_sel)};
            if (chg_sr[1])
                O_param_tgl <= ~O_param_tgl;
        end
    end

    // OSD 打开期间屏蔽翻页
    assign O_block_page = I_sw3;

    //-------------------------------------------------------------------------
    // 参数寄存器
    //-------------------------------------------------------------------------
    // 每按一次的变化量。规格给的是"建议，供你定"。
    // 亮度改成乘法式后范围是 0.15x~1.85x（跨度 109 级）：
    //     步长 5  时每档仅约 11 级，肉眼偏弱 —— 实测就是这个原因导致"感觉调不动"
    //     步长 10 时每档约 21 级，清晰可见  ← 当前
    //   配合 video_enhance 里的帧率缓变，依然是平滑过渡而不是硬跳。
    localparam [6:0] PARAM_STEP = 7'd10;

    //（param_sel 的声明和说明见上面"跨域握手"那一节，这里不再重复声明）

    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) begin
            param_sel    <= 2'd0;
            O_brightness <= 7'd50;      // 中性
            O_contrast   <= 7'd50;      // 1.0x
            O_volume     <= 7'd80;      // 0.80x：够响，同时上下都留出调节余量
        end else if (I_sw3) begin
            // 切换参数（板载 KEY_2）
            // 三页轮转：0 亮度 -> 1 对比度 -> 2 音量 -> 0
            if (I_key1_press)
                param_sel <= (param_sel == 2'd2) ? 2'd0 : (param_sel + 2'd1);

            if (param_sel == 2'd0) begin
                if (I_key2_press) begin             // 板载 KEY_3：亮度 +
                    if (O_brightness < 7'd100)
                        O_brightness <= O_brightness + PARAM_STEP;
                end else if (I_key3_press) begin    // 板载 KEY_4：亮度 −
                    if (O_brightness > 7'd0)
                        O_brightness <= O_brightness - PARAM_STEP;
                end
            end else if (param_sel == 2'd1) begin
                if (I_key2_press) begin             // 板载 KEY_3：对比度 +
                    if (O_contrast < 7'd100)
                        O_contrast <= O_contrast + PARAM_STEP;
                end else if (I_key3_press) begin    // 板载 KEY_4：对比度 −
                    if (O_contrast > 7'd0)
                        O_contrast <= O_contrast - PARAM_STEP;
                end
            end else begin
                if (I_key2_press) begin             // 板载 KEY_3：音量 +
                    if (O_volume < 7'd100)
                        O_volume <= O_volume + PARAM_STEP;
                end else if (I_key3_press) begin    // 板载 KEY_4：音量 −
                    if (O_volume > 7'd0)
                        O_volume <= O_volume - PARAM_STEP;
                end
            end
        end
        // SW3=0 时参数保持不变（退出 OSD 不清值），param_sel 也保持
    end

endmodule
