//=============================================================================
// banner_scroll.v —— 底部滚动标语层 + 字随音频跳动
//
// 在视频管线里的位置
// ------------------
//   video_curl -> banner_scroll -> osd_overlay -> osd_menu -> HDMI
//   放在 osd_overlay 之前，上层天然覆盖本层：
//     · 停止提示条 320x44 与本条带重叠 -> 提示条在上
//     · 参数调节条 280x64 @(180,380) 与条带重叠 -> 调节条在上（条带隐藏）
//
// 显示与滚动
// ----------
//   文字周期 = 屏宽 640 px（320 px 文字 + 320 px 空白），每帧前进 2 px：
//       屏幕第 x 列的周期位置  spos = (x + off) mod 640
//        spos < 320 -> 文字；否则 -> 底带空白
//   速度 2 px/帧 @59.52 Hz = 119 px/s：文字 2.7 s 扫过，空白 2.7 s。
//
//   为什么周期必须等于屏宽：
//     周期 > 640：屏幕有时一段都没有；周期 = 640：恰好一段且永不空（本实现）；
//     周期 < 640：同时出现 2 段以上。所以 320 px 空白是"只显示一段"的最短间隔。
//
// 字模 2× 放大（c67）
// -------------------
//   字模仍是 16x16 1bpp，按 2× 整数放大到 32x32 显示：
//       字序号   gcol = spos[8:5]        （spos/32）
//       字内列   gpx  = spos[4:1]        （spos[4:0]/2）
//       字模行   grow = (y - 字顶) >> 1
//   不重新生成 32x32 字库：ROM 要从 1024x16 涨到 4096x32，BRAM 1 块 -> 约 15 块，
//   本工程 BRAM 只有 31/64 可用。代价是笔画成为 2px 方块。
//   缩放只改位切片，不增加任何逻辑。
//
// 字随音频跳动（c67）
// -------------------
//   驱动来自 osd_audio_env 的 I_level（= v[2]+v[3]，0..118，每帧更新）。
//   整条链是二阶弹簧 + 逐字行波：
//
//       target = max(0, I_level - THR) >> KSH     静音归零、响度映射到行数
//       acc    = (target - pos) >> A_K            刚度
//       vel    = vel + acc - (vel >> D_K)         阻尼
//       pos    = pos + (vel >> B_K)               积分
//       dy[i]  = min(CAP, dly[i])                 只在输出处钳上限
//
//   ★ 为什么用二阶而不是一阶滤波（实测数据，sdcard/01.wav 892 帧）：
//       一阶快升慢降  帧间跳变 p90=2、max=7、无过冲
//       二阶弹簧      帧间跳变 p90=2、max=3、过冲约 8 行（这是 C67 的 THR=14 参数下
//                     的实测；C77 改成 THR=36 后目标中位 11 行，过冲空间只剩 3 行）
//     max 从 7 降到 3 就是"流畅"的实质 —— 一阶只有位置状态，能量突增时会一步
//     跳 7 行（肉眼是一次闪烁）；二阶有速度状态，物理上不可能突变，
//     并带来过冲-回弹的质量感。
//
//   ★ pos **两端都要钳，而且撞界必须清速度**：
//       只钳上界不减速度 -> vel 每帧只衰减 1/8，从 8 归零要 ~50 帧，
//       期间 pos 一直顶着 CAP，看起来像"卡在顶部"而不是弹到顶；
//       不钳上界 -> pos 会冲到 18，输出 min(CAP) 把它压成 14，"在顶部多停 4 帧"。
//       下界同理（pos<0 -> 0 且清 vel），否则字会掉出条带。
//   ★ vel 必须有符号。写成无符号时回落会截断成正数，表现为"字只上不下"。
//
//   逐字行波：延迟线每帧移位一次，长度 10*LAG = 20 级；字 9 取 dly[18]，
//   比字 0 滞后 18 帧 = 302 ms（不是 20 帧 —— dly[19] 从未被读到）。
//   字 i 取 dly[i*LAG]，于是"新值从字 0 进入、向字 9 流动"。
//   ★ 不用"每 LAG 帧移一次"：那样位置每 2 帧才更新一次，会引入 33 ms 的
//     阶梯感（等于把刷新率砍半），与"流畅"的目标相反。多 80 个触发器换来的
//     是字位置逐帧连续。
//
//   为什么要 vs_fall 锁存：I_level 每帧变化一次，但像素时钟下 y 扫描贯穿整帧。
//   若 dy 在帧内改变，会出现"上半帧按旧 dy、下半帧按新 dy"，字形被横向切成两截。
//
// 本文件当前状态 = C77（2026-10-30 18:12 按要求回退）
// ----------------------------------------------------
//   律动只有"垂直位移"一个维度，没有发光、没有怠速呼吸、没有底带呼吸、
//   没有音量门控、没有输出压缩。下面标了三个"已知缺陷"，都是 C78 才修的，
//   回退时一并带了回来（保留原样是为了与 hdmi_media_player_C77.bit 逐位一致，
//   bit 的 Bitstream CRC = 10100010101001101100011101101011）。
//
//   ★ 三个已知缺陷全部保留原样（用户 2026-10-30 22:18 决定：回到 C77，不修）：
//     缺陷 1：字色判据恒假（见"字色"段）—— 重音变亮从未生效过，
//             上板永远同一个金色。
//     缺陷 2：行波索引截断 + 字序号越界（见"跳动位移"段）——
//             字 8/9 读的是 dly[0]/dly[2]，最后两个字的行波是断的。
//     缺陷 3：峰值贴框（字顶 418 压住条带内容首行 418）。
//
//   三者都验证过修法、也实测过代价，记在对应段落里。要修时直接照做即可：
//     参考实现 `_archive/backup_c78_20261030_1702/banner_scroll.v.C79tmp`
//     （C78 全量版，含缺陷 1/2/3 的修法 + 发光/怠速/底带/音量门控）
//
// 门控
// ----
//   I_on      0 = 完全透传（还没有图 / 亮度条占用条带区），连底带都不画
//   I_run     0 = 定格（设置菜单打开 / 提示条显示中）
//   I_bounce  0 = 不跳动（dy 恒 0，回到纯滚动）
//   I_rst_off 单拍清零滚动偏移。当前顶层恒接 0；c72 起换图时的清零改由
//             I_load_busy 的下降沿（busy_fall）在内部完成，见"装载结束时把滚动偏移归零"
//
// 字库
// ----
//   不自带 osd_font_rom，字模由顶层共享字库提供。本层优先级最低。
//=============================================================================

module banner_scroll #(
    parameter [11:0] BAND_Y0 = 12'd416,     // 条带顶（含边框）
    parameter [11:0] BAND_Y1 = 12'd472,     // 条带底（不含）
    parameter [11:0] TXT_Y   = 12'd432,     // 文字行顶（2x 放大后 32px 高）
    parameter [11:0] SCR_W   = 12'd640,     // 屏幕宽
    parameter [11:0] TXT_W   = 12'd320,     // 文字总宽 = 10 字 x 32px

    // ---- 弹簧参数（调观感只改这里，不动逻辑）----
    parameter [3:0]  A_K     = 4'd2,        // 刚度：越小越硬
    parameter [3:0]  D_K     = 4'd3,        // 阻尼：越大越弹
    parameter [3:0]  B_K     = 4'd2,        // 积分
    parameter [4:0]  CAP     = 5'd14,       // 弹簧位移上限（行），pos 撞到它就钳住并清速度
                                            //   14 行时峰值字顶 = 432-14 = 418，正好压住条带
                                            //   内容首行（418）—— 这就是"已知缺陷 3：贴框"。
                                            //   ★ 别想着砍到 11 来修：实测顶死率
                                            //     CAP14 5.7% / CAP12 10.0% / CAP11 21.6%
                                            //     / CAP10 31.7%，砍 CAP 会把"响段钉死在顶"带回来。
    parameter [5:0]  THR     = 6'd36,       // 静音门限 = 映射偏置（2026-10-30 c77）
                                            //   THR=14 时素材 level 中位 80 -> 目标 16.5 行
                                            //   被 CAP=14 削平，31~42% 帧顶死，音量拉不开。
                                            //   36 = (level-36)>>2：响度区间 76~91 铺满
                                            //   9~13 行，峰值 level>96 才短暂触顶（仿真 5.4%）。
    parameter [2:0]  KSH     = 3'd2,        // 灵敏度（右移位数）
    parameter [2:0]  LAG     = 3'd2         // 行波：每字比前一字滞后几帧
                                            //   ★ 当前索引写法 `spos[8:5] * LAG` 有截断缺陷，
                                            //     详见下方"跳动位移"段（缺陷 2）
)(
    input               I_clk,          // video_clk 25MHz
    input               I_rst,

    // ---- 视频（串在像素流中间）----
    input      [23:0]   I_rgb,
    input               I_vs,
    input               I_de,
    output reg [23:0]   O_rgb,
    output reg          O_vs,
    output reg          O_de,

    // ---- 控制 ----
    input               I_on,           // 1 = 显示条带
    input               I_run,          // 1 = 允许滚动（否则定格）
    input               I_rst_off,      // 单拍：偏移清零
    input               I_bounce,       // 1 = 字随音频跳动

    // ---- 音频驱动（来自 osd_audio_env，每帧更新）----
    input      [6:0]    I_level,        // ★ 7 位：v2+v3 最大 118

    // c72：装载进度条。I_load_busy=1 时字幕带整条换成进度条（文字隐藏）
    //   为什么整条换而不是叠在文字下：字幕带 56 行，文字 32 + 条 14 = 46，
    //   塞得下但会挤；而且"文字→进度条→文字"本身就是换页的状态信号。
    input      [7:0]    I_prog,         // 0..255，来自 bmp_load_fat
    input               I_load_busy,    // 1 = 正在装载

    // ---- 字库外置接口 ----
    output      [5:0]   O_fcode,
    output      [3:0]   O_frow,
    output              O_freq,
    input       [15:0]  I_fbits,
    input               I_font_grant
);

    localparam [23:0] C_TEXT   = 24'hF0C040;   // 与 OSD 标题同色
    localparam [23:0] C_BRIGHT = 24'hFFF6D0;   // 重音时的亮色
    localparam [23:0] C_BORDER = 24'h6E788C;
    localparam [7:0]  MASK_R = 8'd12;          // 暗玻璃基色 #0C0F16
    localparam [7:0]  MASK_G = 8'd15;
    localparam [7:0]  MASK_B = 8'd22;

    //-------------------------------------------------------------------------
    // 像素坐标计数（与 osd_menu / osd_overlay 同构，1 拍延迟）
    //-------------------------------------------------------------------------
    reg  [11:0] x_cnt, y_cnt;
    reg         vs_d, de_d;

    wire vs_edge = (I_vs != vs_d);
    wire vs_fall = vs_d & ~I_vs;          // 每帧只有这一个沿用于推进滚动/弹簧
    wire de_fall = de_d & ~I_de;

    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) begin
            x_cnt <= 12'd0;
            y_cnt <= 12'd0;
            vs_d  <= 1'b0;
            de_d  <= 1'b0;
        end else begin
            vs_d <= I_vs;
            de_d <= I_de;
            if (vs_edge) begin
                x_cnt <= 12'd0;
                y_cnt <= 12'd0;
            end else if (!I_de) begin
                x_cnt <= 12'd0;
                if (de_fall)
                    y_cnt <= y_cnt + 12'd1;
            end else begin
                x_cnt <= x_cnt + 12'd1;
            end
        end
    end

    //-------------------------------------------------------------------------
    // 滚动偏移：周期 = 屏宽（640），严格保证"屏幕上只有一段字幕"
    //-------------------------------------------------------------------------
    localparam [9:0] STEP = 10'd2;          // 每帧前进像素（119 px/s @59.52Hz）

    reg [9:0] off;

    // c72：装载结束时把滚动偏移归零
    //   旧版 I_rst_off 恒接 0（"换图不重置，避免 3s 档文字反复跳回起点"），
    //   那条决策在**单一文案**下成立。加了每图文案之后前提变了：
    //   不重置的话观众看到的是"半句话突然换成另一句话的对应位置"，
    //   比重置难看得多。整句从头开始反而符合"翻到新的一页"。
    reg  busy_d;
    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) busy_d <= 1'b0;
        else       busy_d <= I_load_busy;
    end
    wire busy_fall = busy_d & ~I_load_busy;

    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst)
            off <= 10'd0;
        else if (I_rst_off || busy_fall)
            off <= 10'd0;
        else if (I_run && vs_fall)
            off <= (off >= (SCR_W[9:0] - STEP)) ? 10'd0 : (off + STEP);
    end

    //-------------------------------------------------------------------------
    // 弹簧 + 逐字行波（全部在 vs_fall 推进，帧内恒定）
    //-------------------------------------------------------------------------
    reg  [7:0]         sp_pos;          // 0..约 20（可短暂超过 CAP，用于过冲）
    reg  signed [8:0]  sp_vel;          // 速度（必须有符号）
    localparam DLY_N = 10 * LAG;        // 20 级
    reg  [7:0]         dly [0:DLY_N-1]; // 行波延迟线（160 FF）

    // 目标：静音归零 + 灵敏度
    wire [7:0] lvl_eff = (I_level > {2'b0, THR}) ? ({1'b0, I_level} - {2'b0, THR}) : 8'd0;
    wire [7:0] sp_tgt  = (lvl_eff >> KSH);

    // 二阶：acc -> vel -> pos
    wire signed [9:0] sp_acc = ($signed({2'b0, sp_tgt}) - $signed({2'b0, sp_pos})) >>> A_K;
    wire signed [9:0] vel_n  = sp_vel + sp_acc - (sp_vel >>> D_K);
    wire signed [9:0] pos_n  = $signed({1'b0, sp_pos}) + (vel_n >>> B_K);

    // 两端钳位 + 撞界清速度
    //   ★ 为什么上界也要钳：不钳的话 pos 会冲到 18，而输出 min(CAP) 把它压成 14，
    //     结果"字在顶部多停 4 帧"，看起来像卡住而不是弹到顶。
    //   ★ 为什么撞界要清速度：不清的话 vel 每帧只衰减 1/8，从 8 归零要 ~50 帧，
    //     期间 pos 一直顶着 CAP —— 同样表现为"卡在顶部"。
    wire over_cap = (pos_n > $signed({2'b0, CAP}));
    wire under_0  = (pos_n < 0);
    wire [7:0] pos_new = under_0 ? 8'd0 : (over_cap ? {3'b0, CAP} : pos_n[7:0]);

    integer di;
    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) begin
            sp_pos <= 8'd0;
            sp_vel <= 9'sd0;
            for (di = 0; di < DLY_N; di = di + 1)
                dly[di] <= 8'd0;
        end else if (vs_fall) begin
            if (I_bounce) begin
                sp_pos <= pos_new;
                sp_vel <= (under_0 | over_cap) ? 9'sd0 : vel_n;
            end else begin
                sp_pos <= 8'd0;
                sp_vel <= 9'sd0;
            end
            // 行波：每帧整体右移一次，新值进 0 号槽
            //   字 9 取 dly[18]，比字 0 滞后 18 帧（302 ms）
            dly[0] <= I_bounce ? pos_new : 8'd0;
            for (di = 1; di < DLY_N; di = di + 1)
                dly[di] <= dly[di - 1];
        end
    end

    //-------------------------------------------------------------------------
    // 条带与文字判定
    //-------------------------------------------------------------------------
    wire in_band = I_on && (y_cnt >= BAND_Y0) && (y_cnt < BAND_Y1);

    // 条带上下各 1px 边框
    wire in_edge = in_band && ((y_cnt == BAND_Y0) || (y_cnt == BAND_Y1 - 12'd1));

    //-------------------------------------------------------------------------
    // c72：装载进度条
    //   轨道 x=64..575（512 = 256×2，填充宽 = prog<<1，零乘法零除法）
    //   y=437..450（14 行），落在条带内、不碰上下边框
    //-------------------------------------------------------------------------
    localparam [11:0] PB_X0 = 12'd64;
    localparam [11:0] PB_W  = 12'd512;
    localparam [11:0] PB_Y0 = 12'd437;
    localparam [11:0] PB_Y1 = 12'd451;
    localparam [23:0] C_PB_TRACK = 24'h2E3038;

    wire in_pb_y = (y_cnt >= PB_Y0) && (y_cnt < PB_Y1);
    wire in_pb_x = (x_cnt >= PB_X0) && (x_cnt < (PB_X0 + PB_W));
    wire in_pb   = in_band && I_load_busy && in_pb_y && in_pb_x;

    // 填充右端 = X0 + prog*2。prog=255 时只到 64+510=574，差 1px 不满，
    // 所以 255 单独判一次，保证"读满"时轨道填到最右端
    wire [11:0] pb_fill_end = (I_prog == 8'd255)
                            ? (PB_X0 + PB_W)
                            : (PB_X0 + {3'd0, I_prog, 1'b0});
    wire in_pb_fill = in_pb && (x_cnt < pb_fill_end);

    // spos = (x + off) mod 屏宽：屏幕列在"文字周期"里的位置
    //   sum = x + off ∈ [0, 1277]，减 640 一次即可落回 [0, 639]
    wire [10:0] sum = x_cnt[9:0] + off;
    wire [9:0]  spos = (sum >= { 1'b0, SCR_W[9:0] })
                       ? (sum[9:0] - SCR_W[9:0])
                       : sum[9:0];
    wire        in_txt_col = (spos < TXT_W[9:0]);

    //-------------------------------------------------------------------------
    // 跳动位移：按字序号查延迟线，输出处钳上限
    //
    // 索引有两个坑，2026-10-30 18:40 修掉（此前一直带 bug 上板）：
    //
    // ① 乘积位宽被截断。`dly[spos[8:5] * LAG]` 里 spos[8:5] 是 4 位、
    //    LAG 是 3 位参数，Verilog 的自决定上下文规定乘积宽度 = max(4,3) = **4 位**：
    //        ch=7 -> 14 装得下 ✓
    //        ch=8 -> 16 截成 0  ✗  字 8 读到 dly[0]（最新值，等于完全不滞后）
    //        ch=9 -> 18 截成 2  ✗  字 9 读到 dly[2]
    //    表现为"行波在最后两个字断掉"。仿真返回 x、综合不报错、上板只是
    //    后两字跟前面不同步 —— 所以一直没人发现。
    //    修法：两个操作数都显式扩到 5 位，乘积 5 位、最大 18（dly 有 20 级）。
    //
    // ② 字序号越界。spos 是 0..639，[8:5] 会取到 0..15，索引最大 30 -> 越界读。
    //    spos>=320 那些列虽然 in_txt_col=0 不显示，但组合路径照样在读，
    //    仿真读 x、综合器行为未定义。修法：先钳到 9。
    //
    // ★ 这两条都不改变观感设计，只是让最后两个字的行波变得正确
    //   （修复前字 8/9 几乎不滞后，整句的行波是断的）。
    //-------------------------------------------------------------------------
    //-------------------------------------------------------------------------
    // ★★ 已知缺陷 2（**未修复**，2026-10-30 按要求保留 C77 原样）
    //
    //   `dly[spos[8:5] * LAG]` 有两个问题：
    //
    //   ① 乘积位宽被截断。spos[8:5] 是 4 位、LAG 是 3 位参数，Verilog 的自决定
    //      上下文规定乘积宽度 = max(4,3) = **4 位**：
    //          ch=7 -> 14 装得下 ✓
    //          ch=8 -> 16 截成 0  ✗  字 8 读到 dly[0]（最新值，等于完全不滞后）
    //          ch=9 -> 18 截成 2  ✗  字 9 读到 dly[2]
    //      表现为"行波在最后两个字断掉"。仿真返回 x、综合不报错，
    //      上板只表现为后两字跟前面不同步 —— 所以一直没被发现。
    //
    //   ② 字序号越界。spos 是 0..639，[8:5] 会取到 0..15，索引最大 30，
    //      而 dly 只有 20 级 —— 越界读。spos>=320 那些列 in_txt_col=0 不显示，
    //      但组合路径照样在读，仿真读 x、综合器行为未定义。
    //
    //   ★ 修法（已验证过，见 C77b/C77c）：字序号先钳到 9，再把索引写成
    //     `{ch_sel, 1'b0}`（LAG=2 时等价于 ×2，且不实例化乘法器）。
    //     代价：LUT 9,400 -> 9,408、slices 89.06% -> 90.71%、WNS +160ps -> +1ps。
    //     用户 2026-10-30 22:18 决定不付这个代价，保留 C77 原样。
    //-------------------------------------------------------------------------
    wire [7:0] lvl_slot = dly[spos[8:5] * LAG];
    wire [4:0] dy       = (lvl_slot > {3'b0, CAP}) ? CAP : lvl_slot[4:0];

    // 文字顶 = 基线 - dy（dy 是"向上"的行数）
    //   ★ 中间量必须 >= 12 位：432-14 在低 5 位截断会回绕
    wire [11:0] ttop = TXT_Y - {7'd0, dy};
    wire [11:0] tbot = ttop + 12'd32;

    wire in_txt = in_band && in_txt_col &&
                  (y_cnt >= ttop) && (y_cnt < tbot);

    wire [3:0]  gcol = spos[8:5];             // 第几个字。spos>=320 时会取到 10..15，
                                              // 落 case 的 default（空格）—— 那些列本来就
                                              // 落在空白区（in_txt_col=0），不影响显示
    wire [3:0]  gpx  = spos[4:1];             // 字内列号（2x：spos[4:0]/2）
    wire [3:0]  grow = (y_cnt - ttop) >> 1;   // 字模行（2x）

    //-------------------------------------------------------------------------
    // 文字表：「欢 迎 观 看 太 阳 神 鸟 金 饰」
    //-------------------------------------------------------------------------
    reg [5:0] gcode;
    always @(*) begin
        case (gcol)
            4'd0: gcode = 6'd44;   // 欢
            4'd1: gcode = 6'd45;   // 迎
            4'd2: gcode = 6'd26;   // 观
            4'd3: gcode = 6'd27;   // 看
            4'd4: gcode = 6'd46;   // 太
            4'd5: gcode = 6'd47;   // 阳
            4'd6: gcode = 6'd48;   // 神
            4'd7: gcode = 6'd49;   // 鸟
            4'd8: gcode = 6'd50;   // 金
            4'd9: gcode = 6'd51;   // 饰
            default: gcode = 6'd10; // 空格。spos>=320 的空白区会落到这里，
                                    // 但那些列的 in_txt=0（in_txt_col 判掉了），
                                    // 所以只是被选中、不会被画出来
        endcase
    end

    //-------------------------------------------------------------------------
    // 共享字库查表（grant=0 时只画底带、不画字）
    //-------------------------------------------------------------------------
    assign O_fcode = gcode;
    assign O_frow  = grow;
    assign O_freq  = in_txt;

    wire fpix   = I_fbits[4'd15 - gpx] & I_font_grant;
    wire txt_px = in_txt && fpix;

    //-------------------------------------------------------------------------
    // ★ 已知缺陷 1（C78 才修）：字色判据恒假，"重音变亮"从未生效过
    //
    //   原意是"位移 28 行以上算明显重音，把字色切到亮金"。但 sp_pos 被
    //   CAP 钳在 14（撞界就钳住并清速度），**永远到不了 28**：
    //       sp_pos ∈ [0,14]  ->  sp_pos > 28 恒为假  ->  c_text 恒等于 C_TEXT
    //   所以上板看到的字色从头到尾是同一个金色，这 2 级色阶是死逻辑
    //   （综合器会把比较器和 C_BRIGHT 一起剪掉，不占资源，功能上等于不存在）。
    //
    //   ★ 预览工具 tools/make_bounce_preview.py 里写的是 glow = pos/55 连续渐变，
    //     所以**预览一直比上板好看**，差的就是这一层 —— 看预览别指望上板一样。
    //   ★ C78 的修法：按实际 dy 查 4 级色阶，阈值 3/6/9，色 = GOLD + lv*(5,18,48)，
    //     最高级正好等于本文件的 C_BRIGHT（#FFF6D0）。
    //-------------------------------------------------------------------------
    wire [23:0] c_text = (sp_pos > 8'd28) ? C_BRIGHT : C_TEXT;

    //-------------------------------------------------------------------------
    // 暗玻璃底（与 c39 一致的 87.5% 遮罩，保证金色在亮图上可读）
    //-------------------------------------------------------------------------
    wire [7:0] m_r = MASK_R + { 5'd0, I_rgb[23:19] };
    wire [7:0] m_g = MASK_G + { 5'd0, I_rgb[15:11] };
    wire [7:0] m_b = MASK_B + { 5'd0, I_rgb[7:3]   };

    //-------------------------------------------------------------------------
    // 合成（优先级从高到低）
    //   进度条填充 > 进度条轨道 > 文字 > 边框 > 暗底 > 透传
    //   装载期间（I_load_busy）文字让位给进度条：条带只有 56 行，文字 32 + 条 14
    //   虽塞得下但会挤，"文字→进度条→文字"本身就是换页的状态信号。
    //-------------------------------------------------------------------------
    reg [23:0] mix;
    always @(*) begin
        if (!I_on)
            mix = I_rgb;                 // 非显示档：完全透传，连底带都不画
        else if (!in_band)
            mix = I_rgb;
        else if (in_pb_fill)
            mix = C_TEXT;                // c72：进度条填充（与字幕同色）
        else if (in_pb)
            mix = C_PB_TRACK;            // c72：进度条轨道
        else if (txt_px && !I_load_busy)
            mix = c_text;                // 装载期间不画字，让位给进度条
        else if (in_edge)
            mix = C_BORDER;
        else
            mix = { m_r, m_g, m_b };
    end

    always @(posedge I_clk or posedge I_rst) begin
        if (I_rst) begin
            O_rgb <= 24'd0;
            O_vs  <= 1'b0;
            O_de  <= 1'b0;
        end else begin
            O_rgb <= mix;
            O_vs  <= I_vs;
            O_de  <= I_de;
        end
    end

endmodule
